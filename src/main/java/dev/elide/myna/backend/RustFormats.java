  /** Reader and writer machinery shared by every family, driven by the generated tables. */
  private static final String CORE =
      """

          /// The error kinds; codes below 16 are `Unsupported`, below 32 `Limit`, the rest `Malformed`.
          #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
          #[repr(u8)]
          pub enum ErrorKind {
              BadMagic = 1,
              BadVersion = 2,
              BadFingerprint = 3,
              HeaderRejected = 4,
              TooLarge = 16,
              TooManyStrings = 17,
              TooManyNodes = 18,
              FieldTooLong = 19,
              TooDeep = 20,
              TooMuchWork = 21,
              OutOfMemory = 22,
              Truncated = 32,
              BadHeader = 33,
              BadLength = 34,
              BadStringTable = 35,
              BadUtf8 = 36,
              BadIndex = 37,
              BadTag = 38,
              BadNode = 39,
              BadValue = 40,
              BadElement = 41,
              BadString = 42,
              StringOrder = 43,
              BadRef = 44,
              BadRefKind = 45,
              SharedUnique = 46,
              Unreferenced = 47,
              UnusedString = 48,
              BadRoot = 49,
              NodeOrder = 50,
              DuplicateNode = 51,
              DuplicateString = 52,
          }

          /// Whether a file is not for this reader, over a declared limit, or not a valid encoding.
          #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
          pub enum Class {
              Unsupported,
              Limit,
              Malformed,
          }

          impl ErrorKind {
              pub const fn code(self) -> u8 {
                  self as u8
              }

              pub const fn class(self) -> Class {
                  let code = self as u8;
                  if code < 16 {
                      Class::Unsupported
                  } else if code < 32 {
                      Class::Limit
                  } else {
                      Class::Malformed
                  }
              }
          }

          /// A rejected input: the kind, the byte offset of the failed check and the node index
          /// (`u32::MAX` outside a node).
          #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
          pub struct FormatError {
              pub kind: ErrorKind,
              pub offset: u32,
              pub node: u32,
          }

          impl FormatError {
              pub const fn class(&self) -> Class {
                  self.kind.class()
              }
          }

          /// A value the writer cannot encode within the format's rules or limits.
          #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
          pub struct WriteError {
              pub kind: ErrorKind,
          }

          /// The header fields a caller may read before choosing a reader.
          #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
          pub struct Peek {
              pub version: u32,
              pub header_word: u32,
          }

          const NONE: u32 = 0xFFFF_FFFF;
          const UNTAGGED: u32 = 0x1_0000;
          const NO_UNION: usize = usize::MAX;
          const REFERENCED: u16 = 0x8000;
          const K_FIELD: u8 = 0;
          const K_BYTES: u8 = 1;
          const K_STRING: u8 = 2;
          const K_REF: u8 = 3;
          const K_REFS: u8 = 4;
          const K_SCALARS: u8 = 5;
          const K_ELEMENTS: u8 = 6;
          const K_UNION: u8 = 7;

          #[derive(Clone, Copy)]
          enum Check {
              None,
              Bool,
              Values(&'static [u64]),
              Mask(u64),
          }

          #[derive(Clone, Copy)]
          struct M {
              kind: u8,
              width: u8,
              item: u8,
              optional: bool,
              max: u32,
              targets: &'static [u16],
              check: Check,
              list: usize,
          }

          struct N {
              tag: u16,
              unique: bool,
              interned: bool,
              fixed: u32,
              members: &'static [M],
          }

          struct E {
              tag: u32,
              size: u32,
              members: &'static [M],
          }

          struct F {
              magic: u32,
              version: u32,
              fingerprint: u64,
              header: bool,
              max_bytes: u32,
              max_nodes: u32,
              max_strings: u32,
              max_depth: u32,
              max_work: u32,
              accepted: &'static [u16],
              roots: &'static [u16],
          }

          fn node_spec(tag: u16) -> Option<&'static N> {
              NODES.binary_search_by_key(&tag, |n| n.tag).ok().map(|i| &NODES[i])
          }

          fn union_element(union: usize, tag: u16) -> Option<&'static E> {
              UNIONS[union].iter().map(|&e| &ELEMENTS[e as usize]).find(|e| e.tag == tag as u32)
          }

          #[inline]
          fn rd16(b: &[u8], at: usize) -> u16 {
              u16::from_le_bytes([b[at], b[at + 1]])
          }

          #[inline]
          fn rd32(b: &[u8], at: usize) -> u32 {
              u32::from_le_bytes([b[at], b[at + 1], b[at + 2], b[at + 3]])
          }

          #[inline]
          fn rd64(b: &[u8], at: usize) -> u64 {
              rd32(b, at) as u64 | (rd32(b, at + 4) as u64) << 32
          }

          #[inline]
          fn pad4<T: Into<u64>>(n: T) -> usize {
              ((n.into() + 3) & !3) as usize
          }

          fn read_scalar(b: &[u8], at: usize, width: u8) -> u64 {
              match width {
                  1 => b[at] as u64,
                  2 => rd16(b, at) as u64,
                  4 => rd32(b, at) as u64,
                  _ => rd64(b, at),
              }
          }

          fn value_ok(check: Check, v: u64) -> bool {
              match check {
                  Check::None => true,
                  Check::Bool => v <= 1,
                  Check::Values(values) => values.contains(&v),
                  Check::Mask(mask) => v & !mask == 0,
              }
          }

          fn fail(kind: ErrorKind, offset: usize, node: u32) -> FormatError {
              FormatError { kind, offset: offset as u32, node }
          }

          fn peek(b: &[u8], magic: u32) -> Option<Peek> {
              if b.len() < 40 || rd32(b, 0) != magic {
                  return None;
              }
              Some(Peek { version: rd32(b, 4), header_word: rd32(b, 16) })
          }

          /// A validated file's layout. Every read is in bounds once `check` has passed.
          #[derive(Clone, Copy)]
          struct Raw<'a> {
              b: &'a [u8],
              strings: usize,
              string_bytes: usize,
              body: usize,
              index: usize,
              nodes: u32,
          }

          impl<'a> Raw<'a> {
              fn u8(&self, at: usize) -> u8 {
                  self.b[at]
              }

              fn u16(&self, at: usize) -> u16 {
                  rd16(self.b, at)
              }

              fn u32(&self, at: usize) -> u32 {
                  rd32(self.b, at)
              }

              fn u64(&self, at: usize) -> u64 {
                  rd64(self.b, at)
              }

              fn node_at(&self, index: u32) -> usize {
                  self.body + rd32(self.b, self.index + 4 * index as usize) as usize
              }

              fn tag(&self, index: u32) -> u16 {
                  rd16(self.b, self.node_at(index))
              }

              fn string(&self, id: u32) -> &'a str {
                  let id = id as usize;
                  let start = if id == 0 { 0 } else { rd32(self.b, self.strings + 4 * (id - 1)) as usize };
                  let end = rd32(self.b, self.strings + 4 * id) as usize;
                  core::str::from_utf8(&self.b[self.string_bytes + start..self.string_bytes + end]).unwrap_or("")
              }

              fn union_size(&self, union: usize, at: usize, count: usize) -> usize {
                  let mut p = at;
                  for _ in 0..count {
                      p += union_element(union, self.u16(p)).map_or(4, |e| e.size as usize);
                  }
                  p - at
              }
          }

          /// Inline elements of one list, in wire order.
          pub struct Elements<'a, T> {
              raw: Raw<'a>,
              pos: usize,
              left: usize,
              union: usize,
              size: usize,
              make: fn(Raw<'a>, usize) -> T,
          }

          impl<'a, T> Iterator for Elements<'a, T> {
              type Item = T;

              fn next(&mut self) -> Option<T> {
                  if self.left == 0 {
                      return None;
                  }
                  let at = self.pos;
                  self.pos += if self.union == NO_UNION { self.size } else { self.raw.union_size(self.union, at, 1) };
                  self.left -= 1;
                  Some((self.make)(self.raw, at))
              }

              fn size_hint(&self) -> (usize, Option<usize>) {
                  (self.left, Some(self.left))
              }
          }

          impl<'a, T> ExactSizeIterator for Elements<'a, T> {}

          struct Ctx<'s> {
              b: &'s [u8],
              body: usize,
              index: usize,
              string_count: u32,
              next_string: u32,
              meta: Vec<u16>,
              work: Vec<u32>,
              record: bool,
              children: Vec<u32>,
              node: u32,
              depth: u16,
              sum: u32,
          }

          impl<'s> Ctx<'s> {
              fn node_at(&self, i: u32) -> usize {
                  self.body + rd32(self.b, self.index + 4 * i as usize) as usize
              }

              fn string(&mut self, at: usize) -> Result<(), FormatError> {
                  let s = rd32(self.b, at);
                  if s >= self.string_count {
                      return Err(fail(ErrorKind::BadString, at, self.node));
                  }
                  if s > self.next_string {
                      return Err(fail(ErrorKind::StringOrder, at, self.node));
                  }
                  if s == self.next_string {
                      self.next_string += 1;
                  }
                  Ok(())
              }

              fn reference(&mut self, m: &M, at: usize) -> Result<(), FormatError> {
                  let r = rd32(self.b, at);
                  if r == NONE {
                      return if m.optional { Ok(()) } else { Err(fail(ErrorKind::BadRef, at, self.node)) };
                  }
                  if r >= self.node {
                      return Err(fail(ErrorKind::BadRef, at, self.node));
                  }
                  let tag = rd16(self.b, self.node_at(r));
                  if !m.targets.contains(&tag) {
                      return Err(fail(ErrorKind::BadRefKind, at, self.node));
                  }
                  let meta = self.meta[r as usize];
                  if meta & REFERENCED != 0 && node_spec(tag).map_or(false, |n| n.unique) {
                      return Err(fail(ErrorKind::SharedUnique, at, self.node));
                  }
                  self.meta[r as usize] = meta | REFERENCED;
                  let depth = meta & !REFERENCED;
                  if depth > self.depth {
                      self.depth = depth;
                  }
                  self.sum = self.sum.saturating_add(self.work[r as usize]);
                  if self.record {
                      self.children.push(r);
                  }
                  Ok(())
              }

              /// Checks scalar, string and ref members from `at`; returns where they end.
              fn members(&mut self, members: &[M], mut at: usize) -> Result<usize, FormatError> {
                  for m in members {
                      match m.kind {
                          K_FIELD => {
                              if !value_ok(m.check, read_scalar(self.b, at, m.width)) {
                                  return Err(fail(ErrorKind::BadValue, at, self.node));
                              }
                          }
                          K_STRING => self.string(at)?,
                          _ => self.reference(m, at)?,
                      }
                      at += m.width as usize;
                  }
                  Ok(at)
              }

              fn zeros(&self, from: usize, to: usize) -> Result<(), FormatError> {
                  for p in from..to {
                      if self.b[p] != 0 {
                          return Err(fail(ErrorKind::BadNode, p, self.node));
                      }
                  }
                  Ok(())
              }
          }

          fn reserve<T: Clone>(n: usize, fill: Option<T>) -> Result<Vec<T>, FormatError> {
              let mut v = Vec::new();
              v.try_reserve_exact(n).map_err(|_| fail(ErrorKind::OutOfMemory, 0, NONE))?;
              if let Some(x) = fill {
                  v.resize(n, x);
              }
              Ok(v)
          }

          fn check<'a>(b: &'a [u8], f: &F, accept: &[u32], canonical: bool) -> Result<(Raw<'a>, u32), FormatError> {
              use ErrorKind::*;
              let len = b.len();
              if len < 40 {
                  return Err(fail(Truncated, 0, NONE));
              }
              if len as u64 > f.max_bytes as u64 {
                  return Err(fail(TooLarge, 0, NONE));
              }
              if rd32(b, 0) != f.magic {
                  return Err(fail(BadMagic, 0, NONE));
              }
              if rd32(b, 4) != f.version {
                  return Err(fail(BadVersion, 4, NONE));
              }
              if rd64(b, 8) != f.fingerprint {
                  return Err(fail(BadFingerprint, 8, NONE));
              }
              let word = rd32(b, 16);
              if f.header {
                  if !accept.contains(&word) {
                      return Err(fail(HeaderRejected, 16, NONE));
                  }
              } else if word != 0 {
                  return Err(fail(BadHeader, 16, NONE));
              }
              if rd32(b, 36) != 0 {
                  return Err(fail(BadHeader, 36, NONE));
              }
              let sc = rd32(b, 20);
              let sb = rd32(b, 24);
              let nc = rd32(b, 28);
              let bb = rd32(b, 32);
              if sc > f.max_strings {
                  return Err(fail(TooManyStrings, 20, NONE));
              }
              if nc > f.max_nodes {
                  return Err(fail(TooManyNodes, 28, NONE));
              }
              if nc == 0 {
                  return Err(fail(BadLength, 28, NONE));
              }
              if bb % 4 != 0 {
                  return Err(fail(BadLength, 32, NONE));
              }
              let total = 40 + 4 * sc as u64 + pad4(sb) as u64 + bb as u64 + 4 * nc as u64;
              if total != len as u64 {
                  return Err(fail(BadLength, 0, NONE));
              }
              let ends = 40usize;
              let sbytes = ends + 4 * sc as usize;
              let body = sbytes + pad4(sb);
              let index = body + bb as usize;
              let mut prev = 0u32;
              for i in 0..sc as usize {
                  let e = rd32(b, ends + 4 * i);
                  if e < prev {
                      return Err(fail(BadStringTable, ends + 4 * i, NONE));
                  }
                  prev = e;
              }
              if prev != sb {
                  return Err(fail(BadStringTable, if sc == 0 { 24 } else { ends + 4 * (sc as usize - 1) }, NONE));
              }
              for p in sbytes + sb as usize..body {
                  if b[p] != 0 {
                      return Err(fail(BadStringTable, p, NONE));
                  }
              }
              let mut start = 0usize;
              for i in 0..sc as usize {
                  let e = rd32(b, ends + 4 * i) as usize;
                  if core::str::from_utf8(&b[sbytes + start..sbytes + e]).is_err() {
                      return Err(fail(BadUtf8, sbytes + start, NONE));
                  }
                  start = e;
              }
              let mut prev_off = 0u32;
              for i in 0..nc {
                  let ip = index + 4 * i as usize;
                  let off = rd32(b, ip);
                  if off % 4 != 0 || (i == 0 && off != 0) || (i > 0 && off <= prev_off) || off >= bb {
                      return Err(fail(BadIndex, ip, i));
                  }
                  prev_off = off;
              }
              let n = nc as usize;
              let mut cx = Ctx {
                  b,
                  body,
                  index,
                  string_count: sc,
                  next_string: 0,
                  meta: reserve(n, Some(0u16))?,
                  work: reserve(n, Some(0u32))?,
                  record: canonical,
                  children: if canonical { reserve(bb as usize / 4, None)? } else { Vec::new() },
                  node: 0,
                  depth: 0,
                  sum: 0,
              };
              let mut starts: Vec<u32> = if canonical { reserve(n + 1, None)? } else { Vec::new() };
              for i in 0..nc {
                  cx.node = i;
                  cx.depth = 0;
                  cx.sum = 0;
                  if canonical {
                      starts.push(cx.children.len() as u32);
                  }
                  let at = cx.node_at(i);
                  let end = if i + 1 < nc { cx.node_at(i + 1) } else { index };
                  let tag = rd16(b, at);
                  let spec = match node_spec(tag) {
                      Some(s) if f.accepted.contains(&tag) => s,
                      _ => return Err(fail(BadTag, at, i)),
                  };
                  if rd16(b, at + 2) != 0 {
                      return Err(fail(BadNode, at + 2, i));
                  }
                  let fixed_end = at + spec.fixed as usize;
                  let padded = at + pad4(spec.fixed);
                  if padded > end {
                      return Err(fail(BadNode, at, i));
                  }
                  let mut pos = at + 4;
                  for m in spec.members {
                      match m.kind {
                          K_FIELD | K_STRING | K_REF => {
                              cx.members(core::slice::from_ref(m), pos)?;
                          }
                          _ => {
                              if m.max != 0 && rd32(b, pos) > m.max {
                                  return Err(fail(FieldTooLong, pos, i));
                              }
                          }
                      }
                      pos += m.width as usize;
                  }
                  cx.zeros(fixed_end, padded)?;
                  pos = padded;
                  let mut slot = at + 4;
                  for m in spec.members {
                      let variable = match m.kind {
                          K_FIELD | K_STRING | K_REF => false,
                          _ => true,
                      };
                      if variable {
                          let c = rd32(b, slot) as u64;
                          let least = match m.kind {
                              K_BYTES => c,
                              K_SCALARS => c * m.item as u64,
                              K_ELEMENTS => c * ELEMENTS[m.list].size as u64,
                              _ => 4 * c,
                          };
                          if pos as u64 + least > end as u64 {
                              return Err(fail(BadNode, slot, i));
                          }
                          let c = c as usize;
                          let mut payload_end = pos + least as usize;
                          match m.kind {
                              K_REFS => {
                                  for k in 0..c {
                                      cx.reference(m, pos + 4 * k)?;
                                  }
                              }
                              K_ELEMENTS => {
                                  let e = &ELEMENTS[m.list];
                                  for k in 0..c {
                                      let base = pos + k * e.size as usize;
                                      let members_end = cx.members(e.members, base)?;
                                      cx.zeros(members_end, base + e.size as usize)?;
                                  }
                              }
                              K_UNION => {
                                  let mut p = pos;
                                  for _ in 0..c {
                                      if p + 4 > end {
                                          return Err(fail(BadNode, p, i));
                                      }
                                      let e = match union_element(m.list, rd16(b, p)) {
                                          Some(e) => e,
                                          None => return Err(fail(BadElement, p, i)),
                                      };
                                      if rd16(b, p + 2) != 0 {
                                          return Err(fail(BadElement, p + 2, i));
                                      }
                                      if p + e.size as usize > end {
                                          return Err(fail(BadNode, p, i));
                                      }
                                      let members_end = cx.members(e.members, p + 4)?;
                                      cx.zeros(members_end, p + e.size as usize)?;
                                      p += e.size as usize;
                                  }
                                  payload_end = p;
                              }
                              _ => {}
                          }
                          let padded = pad4(payload_end as u64);
                          if padded > end {
                              return Err(fail(BadNode, payload_end, i));
                          }
                          cx.zeros(payload_end, padded)?;
                          pos = padded;
                      }
                      slot += m.width as usize;
                  }
                  if pos != end {
                      return Err(fail(BadNode, pos, i));
                  }
                  let depth = cx.depth + 1;
                  if depth as u32 > f.max_depth {
                      return Err(fail(TooDeep, at, i));
                  }
                  let work = cx.sum.saturating_add(1);
                  if work > f.max_work {
                      return Err(fail(TooMuchWork, at, i));
                  }
                  cx.meta[i as usize] = depth;
                  cx.work[i as usize] = work;
              }
              for i in 0..nc - 1 {
                  if cx.meta[i as usize] & REFERENCED == 0 {
                      return Err(fail(Unreferenced, cx.node_at(i), i));
                  }
              }
              if cx.next_string != sc {
                  return Err(fail(UnusedString, ends + 4 * cx.next_string as usize, NONE));
              }
              let root = cx.node_at(nc - 1);
              if !f.roots.contains(&rd16(b, root)) {
                  return Err(fail(BadRoot, root, nc - 1));
              }
              let raw = Raw { b, strings: ends, string_bytes: sbytes, body, index, nodes: nc };
              if canonical {
                  starts.push(cx.children.len() as u32);
                  canonical_form(&raw, &cx, &starts, f)?;
              }
              Ok((raw, word))
          }

          fn extent<'a>(raw: &Raw<'a>, i: u32) -> &'a [u8] {
              let end = if i + 1 < raw.nodes { raw.node_at(i + 1) } else { raw.index };
              &raw.b[raw.node_at(i)..end]
          }

          fn string_bytes<'a>(raw: &Raw<'a>, id: u32) -> &'a [u8] {
              raw.string(id).as_bytes()
          }

          /// The smallest index `j` with an equal earlier entry, given ids sorted by content then index.
          fn first_duplicate<'a>(ids: &[u32], content: impl Fn(u32) -> &'a [u8]) -> Option<u32> {
              let mut found: Option<u32> = None;
              for w in ids.windows(2) {
                  if content(w[0]) == content(w[1]) && found.map_or(true, |j| w[1] < j) {
                      found = Some(w[1]);
                  }
              }
              found
          }

          fn canonical_form(raw: &Raw<'_>, cx: &Ctx<'_>, starts: &[u32], f: &F) -> Result<(), FormatError> {
              use ErrorKind::*;
              let mut stack: Vec<(u32, u32)> = reserve(f.max_depth as usize + 1, None)?;
              let mut counter = 0u32;
              let root = raw.nodes - 1;
              stack.push((root, starts[root as usize]));
              while let Some(top) = stack.last_mut() {
                  let (node, k) = *top;
                  if k < starts[node as usize + 1] {
                      top.1 = k + 1;
                      let child = cx.children[k as usize];
                      if child >= counter {
                          stack.push((child, starts[child as usize]));
                      }
                  } else {
                      stack.pop();
                      if node != counter {
                          return Err(fail(NodeOrder, raw.node_at(node), node));
                      }
                      counter += 1;
                  }
              }
              let mut ids: Vec<u32> = reserve(raw.nodes as usize, None)?;
              for i in 0..raw.nodes {
                  if node_spec(raw.tag(i)).map_or(false, |n| n.interned) {
                      ids.push(i);
                  }
              }
              ids.sort_by(|&x, &y| extent(raw, x).cmp(extent(raw, y)).then(x.cmp(&y)));
              if let Some(j) = first_duplicate(&ids, |i| extent(raw, i)) {
                  return Err(fail(DuplicateNode, raw.node_at(j), j));
              }
              let mut strings: Vec<u32> = reserve(cx.string_count as usize, None)?;
              strings.extend(0..cx.string_count);
              strings.sort_by(|&x, &y| string_bytes(raw, x).cmp(string_bytes(raw, y)).then(x.cmp(&y)));
              if let Some(j) = first_duplicate(&strings, |i| string_bytes(raw, i)) {
                  let start = if j == 0 { 0 } else { rd32(raw.b, raw.strings + 4 * (j as usize - 1)) as usize };
                  return Err(fail(DuplicateString, raw.string_bytes + start, NONE));
              }
              Ok(())
          }

          // ------------------------------------------------------------ writer core

          struct Rec {
              tag: u16,
              bytes: Vec<u8>,
              /// (offset, is a node reference) of every string id and present reference, in wire order.
              patches: Vec<(u32, bool)>,
              depth: u32,
              work: u32,
          }

          struct Enc {
              bytes: Vec<u8>,
              patches: Vec<(u32, bool)>,
          }

          impl Enc {
              fn new(tag: u16) -> Self {
                  let mut bytes = Vec::new();
                  bytes.extend_from_slice(&tag.to_le_bytes());
                  bytes.extend_from_slice(&[0, 0]);
                  Enc { bytes, patches: Vec::new() }
              }

              fn u8(&mut self, v: u8) {
                  self.bytes.push(v);
              }

              fn u16(&mut self, v: u16) {
                  self.bytes.extend_from_slice(&v.to_le_bytes());
              }

              fn u32(&mut self, v: u32) {
                  self.bytes.extend_from_slice(&v.to_le_bytes());
              }

              fn u64(&mut self, v: u64) {
                  self.bytes.extend_from_slice(&v.to_le_bytes());
              }

              fn raw(&mut self, v: &[u8]) {
                  self.bytes.extend_from_slice(v);
              }

              fn string(&mut self, id: u32) {
                  self.patches.push((self.bytes.len() as u32, false));
                  self.u32(id);
              }

              fn node(&mut self, id: u32) {
                  self.patches.push((self.bytes.len() as u32, true));
                  self.u32(id);
              }

              fn pad(&mut self) {
                  while self.bytes.len() % 4 != 0 {
                      self.bytes.push(0);
                  }
              }
          }

          fn count(n: usize, max: u32) -> Result<u32, WriteError> {
              if n > max as usize {
                  return Err(WriteError { kind: ErrorKind::FieldTooLong });
              }
              Ok(n as u32)
          }

          #[derive(Default)]
          struct Core {
              strings: Vec<String>,
              string_ids: BTreeMap<String, u32>,
              nodes: Vec<Rec>,
              interned: BTreeMap<Vec<u8>, u32>,
          }

          impl Core {
              fn intern(&mut self, text: &str) -> u32 {
                  if let Some(&id) = self.string_ids.get(text) {
                      return id;
                  }
                  let id = self.strings.len() as u32;
                  self.strings.push(String::from(text));
                  self.string_ids.insert(String::from(text), id);
                  id
              }

              fn string_ref(&self, id: u32) -> Result<u32, WriteError> {
                  if (id as usize) < self.strings.len() { Ok(id) } else { Err(WriteError { kind: ErrorKind::BadString }) }
              }

              fn node_ref(&self, id: u32) -> Result<u32, WriteError> {
                  if (id as usize) < self.nodes.len() { Ok(id) } else { Err(WriteError { kind: ErrorKind::BadRef }) }
              }

              fn push(&mut self, mut e: Enc, interned: bool) -> Result<u32, WriteError> {
                  e.pad();
                  if interned {
                      if let Some(&id) = self.interned.get(&e.bytes) {
                          return Ok(id);
                      }
                  }
                  let mut depth = 0u32;
                  let mut work = 0u32;
                  for &(at, is_ref) in &e.patches {
                      if is_ref {
                          let child = &self.nodes[rd32(&e.bytes, at as usize) as usize];
                          depth = depth.max(child.depth);
                          work = work.saturating_add(child.work);
                      }
                  }
                  let id = self.nodes.len() as u32;
                  if interned {
                      self.interned.insert(e.bytes.clone(), id);
                  }
                  let tag = rd16(&e.bytes, 0);
                  self.nodes.push(Rec { tag, bytes: e.bytes, patches: e.patches, depth: depth.saturating_add(1), work: work.saturating_add(1) });
                  Ok(id)
              }

              fn finish(&self, root: u32, f: &F, header: u32) -> Result<Vec<u8>, WriteError> {
                  use ErrorKind::*;
                  let err = |kind| Err(WriteError { kind });
                  let rec = match self.nodes.get(root as usize) {
                      Some(r) => r,
                      None => return err(BadRef),
                  };
                  if !f.roots.contains(&rec.tag) {
                      return err(BadRoot);
                  }
                  if rec.depth > f.max_depth {
                      return err(TooDeep);
                  }
                  if rec.work > f.max_work {
                      return err(TooMuchWork);
                  }
                  // Depth-first post-order from the root, references in wire order.
                  let mut placed = alloc::vec![NONE; self.nodes.len()];
                  let mut order: Vec<u32> = Vec::new();
                  let mut stack: Vec<(u32, usize)> = alloc::vec![(root, 0)];
                  while let Some(top) = stack.last_mut() {
                      let (node, k) = *top;
                      let rec = &self.nodes[node as usize];
                      match rec.patches[k..].iter().position(|p| p.1) {
                          Some(skip) => {
                              let (at, _) = rec.patches[k + skip];
                              top.1 = k + skip + 1;
                              let child = rd32(&rec.bytes, at as usize);
                              if placed[child as usize] == NONE {
                                  stack.push((child, 0));
                              }
                          }
                          None => {
                              stack.pop();
                              placed[node as usize] = order.len() as u32;
                              order.push(node);
                          }
                      }
                  }
                  if order.len() as u64 > f.max_nodes as u64 {
                      return err(TooManyNodes);
                  }
                  // Strings in order of first use.
                  let mut string_ids = alloc::vec![NONE; self.strings.len()];
                  let mut strings: Vec<u32> = Vec::new();
                  for &node in &order {
                      let rec = &self.nodes[node as usize];
                      for &(at, is_ref) in &rec.patches {
                          if !is_ref {
                              let s = rd32(&rec.bytes, at as usize) as usize;
                              if string_ids[s] == NONE {
                                  string_ids[s] = strings.len() as u32;
                                  strings.push(s as u32);
                              }
                          }
                      }
                  }
                  if strings.len() as u64 > f.max_strings as u64 {
                      return err(TooManyStrings);
                  }
                  let string_bytes: usize = strings.iter().map(|&s| self.strings[s as usize].len()).sum();
                  let body: usize = order.iter().map(|&n| self.nodes[n as usize].bytes.len()).sum();
                  let total = 40 + 4 * strings.len() + pad4(string_bytes as u64) + body + 4 * order.len();
                  if total as u64 > f.max_bytes as u64 {
                      return err(TooLarge);
                  }
                  let mut out: Vec<u8> = Vec::with_capacity(total);
                  out.extend_from_slice(&f.magic.to_le_bytes());
                  out.extend_from_slice(&f.version.to_le_bytes());
                  out.extend_from_slice(&f.fingerprint.to_le_bytes());
                  out.extend_from_slice(&(if f.header { header } else { 0 }).to_le_bytes());
                  out.extend_from_slice(&(strings.len() as u32).to_le_bytes());
                  out.extend_from_slice(&(string_bytes as u32).to_le_bytes());
                  out.extend_from_slice(&(order.len() as u32).to_le_bytes());
                  out.extend_from_slice(&(body as u32).to_le_bytes());
                  out.extend_from_slice(&0u32.to_le_bytes());
                  let mut end = 0u32;
                  for &s in &strings {
                      end += self.strings[s as usize].len() as u32;
                      out.extend_from_slice(&end.to_le_bytes());
                  }
                  for &s in &strings {
                      out.extend_from_slice(self.strings[s as usize].as_bytes());
                  }
                  while out.len() % 4 != 0 {
                      out.push(0);
                  }
                  let body_start = out.len();
                  let mut offsets: Vec<u32> = Vec::with_capacity(order.len());
                  for &node in &order {
                      let rec = &self.nodes[node as usize];
                      offsets.push((out.len() - body_start) as u32);
                      let base = out.len();
                      out.extend_from_slice(&rec.bytes);
                      for &(at, is_ref) in &rec.patches {
                          let at = base + at as usize;
                          let old = rd32(&out, at) as usize;
                          let new = if is_ref { placed[old] } else { string_ids[old] };
                          out[at..at + 4].copy_from_slice(&new.to_le_bytes());
                      }
                  }
                  for o in offsets {
                      out.extend_from_slice(&o.to_le_bytes());
                  }
                  Ok(out)
              }
          }
      """;
