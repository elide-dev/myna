package dev.elide.myna.backend;

import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.Fingerprint;
import java.util.ArrayList;
import java.util.List;

/**
 * The C context of the Native Image class, {@code <Class>Directives}. It embeds this generation's
 * {@code seam.h}, writes it to a temporary directory when the image builder first asks for headers
 * and delegates everything else to the consumer's {@code c_context}, if one is named. It is not a
 * {@code Feature}: the header check is the Native Image class's {@code seamHeaderCheck()}, a
 * {@code @CConstant} naming a macro only this generation's header defines.
 *
 * <p>Only the image builder uses the class, and only when the Native Image class is in the image:
 * that class's {@code @CContext} is the sole reference. Run-time code never reaches it, so no
 * header text reaches an image. The class names everything qualified, so neither a declared type
 * nor a consumer class in the package can shadow an import.
 */
public final class NativeImageDirectives implements Backend {
  /**
   * The largest piece of {@code seam.h} held by one string constant, in UTF-8 bytes. A class file
   * holds at most 65535 bytes per constant; a quarter of that leaves room for any encoding.
   */
  public static final int PIECE = 16 * 1024;

  public String filename(Module module) {
    return module.directivesClass() + ".java";
  }

  public String generate(Module m) {
    return generate(m, new Fingerprint(m));
  }

  public String generate(Module m, Fingerprint abi) {
    return withHeader(m, new CHeader().header(m, abi));
  }

  /**
   * The directives class embedding {@code header}, the {@code seam.h} that {@link CHeader}
   * generated for exactly {@code m}: a generation passes the header it already wrote rather than
   * building it a second time. Throws if {@code header} was generated for another module instance.
   */
  public String withHeader(Module m, CHeader.Generated header) {
    header.requireFor(m);
    String self = m.directivesClass();
    String delegate = m.nativeConfig() == null ? null : m.nativeConfig().cContext();
    List<String> pieces = pieces(header.text(), PIECE);
    var out =
        new StringBuilder(
            "// Generated by myna. Used by the Native Image builder only; never reached at run"
                + " time.\n"
                + "package "
                + m.javaPackageName()
                + ";\n\n"
                + "/**\n"
                + " * The C context of {@link "
                + m.nativeClass()
                + "}: the seam.h these bindings were generated with,"
                + (delegate == null ? "" : " after the headers of {@code " + delegate + "},")
                + "\n"
                + " * which the image build's C query checks against the fingerprinted macro the"
                + " bindings read.\n"
                + " */\n"
                + "public final class "
                + self
                + " implements org.graalvm.nativeimage.c.CContext.Directives {\n");
    out.append("    /** seam.h, in pieces of at most ")
        .append(PIECE / 1024)
        .append(" KiB: one class-file string constant holds at most 64 KiB. */\n");
    for (int i = 0; i < pieces.size(); i++) {
      out.append("    private static final String HEADER_").append(i).append(" =");
      List<String> lines = lines(pieces.get(i));
      for (int l = 0; l < lines.size(); l++)
        out.append(l == 0 ? "\n        " : "\n            + ").append(literal(lines.get(l)));
      out.append(";\n");
    }
    if (delegate != null)
      out.append("    private final org.graalvm.nativeimage.c.CContext.Directives context =\n")
          .append("        new ")
          .append(delegate)
          .append("();\n");
    out.append("\n    public ").append(self).append("() {}\n\n");
    out.append(
        "    /** seam.h, written once per builder JVM to a directory removed when that JVM exits."
            + " */\n"
            + "    private static final class Header {\n"
            + "        static final String INCLUDE = write();\n\n"
            + "        private static String write() {\n"
            + "            try {\n"
            + "                java.nio.file.Path directory =\n"
            + "                   "
            + " java.nio.file.Files.createTempDirectory(\"myna-seam\").toAbsolutePath();\n"
            + "                java.nio.file.Path file = directory.resolve(\"seam.h\");\n"
            + "                Runtime.getRuntime().addShutdownHook(new Thread(() -> {\n"
            + "                    try {\n"
            + "                        java.nio.file.Files.deleteIfExists(file);\n"
            + "                        java.nio.file.Files.deleteIfExists(directory);\n"
            + "                    } catch (java.io.IOException ignored) {\n"
            + "                        // The builder is exiting; nothing else can be done.\n"
            + "                    }\n"
            + "                }));\n"
            + "                java.nio.file.Files.writeString(file, String.join(\"\"");
    for (int i = 0; i < pieces.size(); i++) out.append(", HEADER_").append(i);
    out.append(
        "));\n"
            + "                return \"\\\"\" + file + \"\\\"\";\n"
            + "            } catch (java.io.IOException e) {\n"
            + "                throw new java.io.UncheckedIOException(e);\n"
            + "            }\n"
            + "        }\n"
            + "    }\n\n");
    if (delegate == null)
      out.append(
          "    @Override\n"
              + "    public java.util.List<String> getHeaderFiles() {\n"
              + "        return java.util.List.of(Header.INCLUDE);\n"
              + "    }\n\n");
    else {
      out.append(
          "    @Override\n"
              + "    public boolean isInConfiguration() {\n"
              + "        return context.isInConfiguration();\n"
              + "    }\n\n"
              + "    /** The consumer context's headers first, then seam.h. */\n"
              + "    @Override\n"
              + "    public java.util.List<String> getHeaderFiles() {\n"
              + "        var headers = new java.util.ArrayList<String>(context.getHeaderFiles());\n"
              + "        headers.add(Header.INCLUDE);\n"
              + "        return headers;\n"
              + "    }\n\n");
      for (String method :
          List.of("getMacroDefinitions", "getOptions", "getLibraries", "getLibraryPaths"))
        out.append("    @Override\n    public java.util.List<String> ")
            .append(method)
            .append("() {\n        return context.")
            .append(method)
            .append("();\n    }\n\n");
    }
    // Drop the blank line after the last method.
    out.setLength(out.length() - 1);
    out.append("}\n");
    return out.toString();
  }

  /** Lines of text, each keeping its line feed. */
  private static List<String> lines(String text) {
    var lines = new ArrayList<String>();
    int start = 0;
    for (int i = 0; i < text.length(); i++)
      if (text.charAt(i) == '\n') {
        lines.add(text.substring(start, i + 1));
        start = i + 1;
      }
    if (start < text.length() || lines.isEmpty()) lines.add(text.substring(start));
    return lines;
  }

  private static int utf8(int codePoint) {
    return codePoint < 0x80 ? 1 : codePoint < 0x800 ? 2 : codePoint < 0x10000 ? 3 : 4;
  }

  /**
   * Splits text into pieces of at most {@code limit} UTF-8 bytes, at line ends where a line fits
   * and never inside a character. Joined, the pieces are the text; there is always one.
   */
  public static List<String> pieces(String text, int limit) {
    var pieces = new ArrayList<String>();
    var piece = new StringBuilder();
    int size = 0;
    for (String line : lines(text)) {
      int bytes = line.codePoints().map(NativeImageDirectives::utf8).sum();
      if (size + bytes > limit && size > 0) {
        pieces.add(piece.toString());
        piece.setLength(0);
        size = 0;
      }
      if (bytes <= limit) {
        piece.append(line);
        size += bytes;
        continue;
      }
      for (int i = 0; i < line.length(); ) {
        int codePoint = line.codePointAt(i), width = utf8(codePoint);
        if (size + width > limit) {
          pieces.add(piece.toString());
          piece.setLength(0);
          size = 0;
        }
        piece.appendCodePoint(codePoint);
        size += width;
        i += Character.charCount(codePoint);
      }
    }
    if (size > 0 || pieces.isEmpty()) pieces.add(piece.toString());
    return pieces;
  }

  /**
   * A Java string literal of text, in ASCII. Unicode escapes are used only above ASCII: javac
   * translates them before lexing, so one may never spell a quote, a backslash or a line end.
   */
  public static String literal(String text) {
    var out = new StringBuilder(text.length() + 2).append('"');
    for (int i = 0; i < text.length(); i++) {
      char c = text.charAt(i);
      switch (c) {
        case '"' -> out.append("\\\"");
        case '\\' -> out.append("\\\\");
        case '\n' -> out.append("\\n");
        case '\r' -> out.append("\\r");
        case '\t' -> out.append("\\t");
        default -> {
          if (c < 0x20 || c == 0x7f) out.append(String.format("\\%03o", (int) c));
          else if (c > 0x7f) out.append(String.format("\\u%04x", (int) c));
          else out.append(c);
        }
      }
    }
    return out.append('"').toString();
  }
}
