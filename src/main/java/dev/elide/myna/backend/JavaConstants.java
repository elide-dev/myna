package dev.elide.myna.backend;

import dev.elide.myna.model.Names;
import dev.elide.myna.model.Seam.*;
import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.SeamJson;
import java.math.BigInteger;
import java.util.Locale;

/**
 * {@code <Class>Constants.java}: the descriptor's consts, enum values and flag masks as literal
 * {@code static final} primitives, with flag predicates and name functions. Every field is a JLS
 * compile-time constant, so javac inlines it into consumer bytecode and it works as a {@code case}
 * label; the class has no imports, no static initializer and no objects, so it serves HotSpot FFM,
 * Truffle and Native Image consumers alike and is never listed in {@code native-image.properties}.
 */
public final class JavaConstants implements Backend {
  /** True when the module declares anything this class would carry. */
  public static boolean applies(Module m) {
    return !m.constants().isEmpty() || !m.enums().isEmpty() || !m.flagSets().isEmpty();
  }

  public String filename(Module module) {
    return module.constantsClass() + ".java";
  }

  public String generate(Module m) {
    var out =
        new StringBuilder(
            "// Generated by myna. Unsigned integer carriers preserve their raw bits.\n"
                + "package "
                + m.javaPackageName()
                + ";\n\n"
                + "/** Named constants of seam "
                + m.name()
                + ": literal primitives, no imports, no static initializer. */\n"
                + "public final class "
                + m.constantsClass()
                + " {\n    private "
                + m.constantsClass()
                + "() {}\n");
    for (Constant c : m.constants())
      field(
          out,
          "    ",
          "const " + c.name() + ": " + c.type().text(),
          c.type(),
          c.name().toUpperCase(Locale.ROOT),
          Types.javaLiteral(c.type(), c.value(), c.type().text().startsWith("u")));
    for (EnumGroup e : m.enums()) enumGroup(e, out);
    for (FlagSet f : m.flagSets()) flagSet(f, out);
    return out.append("}\n").toString();
  }

  private static void field(
      StringBuilder out, String indent, String doc, Scalar type, String name, String literal) {
    if (doc != null) out.append(indent).append("/** ").append(doc).append(" */\n");
    out.append(indent)
        .append("public static final ")
        .append(Types.java(type))
        .append(' ')
        .append(name)
        .append(" = ")
        .append(literal)
        .append(";\n");
  }

  private static void nested(StringBuilder out, String kind, String name, Scalar type) {
    out.append("\n    /** ")
        .append(kind)
        .append(' ')
        .append(name)
        .append(": ")
        .append(type.text())
        .append(" */\n    public static final class ")
        .append(name)
        .append(" {\n        private ")
        .append(name)
        .append("() {}\n");
  }

  private static void enumGroup(EnumGroup e, StringBuilder out) {
    nested(out, "enum", e.name(), e.type());
    for (EnumValue v : e.values())
      field(
          out,
          "        ",
          null,
          e.type(),
          v.name().toUpperCase(Locale.ROOT),
          Types.javaLiteral(e.type(), v.value(), false));
    String carrier = Types.java(e.type());
    out.append(
            "        /** The declared name of {@code value}, or null for an unlisted value. */\n")
        .append("        public static String name(")
        .append(carrier)
        .append(" value) {\n");
    if (carrier.equals("long")) {
      // Java has no switch over long.
      for (EnumValue v : e.values())
        out.append("            if (value == ")
            .append(v.name().toUpperCase(Locale.ROOT))
            .append(") return ")
            .append(SeamJson.quote(v.name()))
            .append(";\n");
      out.append("            return null;\n");
    } else {
      out.append("            return switch (value) {\n");
      for (EnumValue v : e.values())
        out.append("                case ")
            .append(v.name().toUpperCase(Locale.ROOT))
            .append(" -> ")
            .append(SeamJson.quote(v.name()))
            .append(";\n");
      out.append("                default -> null;\n            };\n");
    }
    out.append("        }\n    }\n");
  }

  private static void flagSet(FlagSet f, StringBuilder out) {
    nested(out, "flags", f.name(), f.type());
    BigInteger all = BigInteger.ZERO;
    for (FlagBit b : f.bits()) {
      BigInteger mask = BigInteger.ONE.shiftLeft(b.bit());
      all = all.or(mask);
      field(
          out,
          "        ",
          null,
          f.type(),
          b.name().toUpperCase(Locale.ROOT),
          Types.javaLiteral(f.type(), mask, true));
    }
    field(out, "        ", null, f.type(), "ALL", Types.javaLiteral(f.type(), all, true));
    String carrier = Types.java(f.type());
    for (FlagBit b : f.bits())
      predicate(out, Names.lowerCamel(b.name()), carrier, b.name().toUpperCase(Locale.ROOT));
    out.append("        /** True when {@code flags} has a bit no declared flag names. */\n");
    predicate(out, "hasUnknown", carrier, "~ALL");
    out.append("    }\n");
  }

  private static void predicate(StringBuilder out, String name, String carrier, String mask) {
    out.append("        public static boolean ")
        .append(name)
        .append('(')
        .append(carrier)
        .append(" flags) { return (flags & ")
        .append(mask)
        .append(") != 0; }\n");
  }
}
