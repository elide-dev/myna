package dev.elide.myna.backend;

import dev.elide.myna.model.Seam;
import dev.elide.myna.model.Seam.*;
import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.SeamJson;
import dev.elide.myna.validate.Validator;
import java.math.BigInteger;
import java.util.Locale;

public final class RustFfi implements Backend {
  public String filename(Module module) {
    return "seam.rs";
  }

  /**
   * A safe slice accessor per counted view: a {@code &Record} is already trusted, and its contract
   * is that a non-null pointer addresses {@code count} elements living as long as the record. The
   * null and size rules are checked once here, with {@code debug_assert!} for the contract parts.
   */
  private static void views(Module m, Struct s, StringBuilder out) {
    var views = Views.of(m, s);
    if (views.isEmpty()) return;
    out.append("impl ").append(s.name()).append(" {\n");
    for (Views v : views) {
      String pointer = "self." + v.pointer().name();
      String count = "self." + v.count().name();
      String element = Types.rust(v.element());
      out.append("    /// The `")
          .append(v.count().name())
          .append("` elements at `")
          .append(v.pointer().name())
          .append("`, empty when it is null.\n")
          .append("    ///\n")
          .append("    /// The record's contract: a non-null `")
          .append(v.pointer().name())
          .append("` addresses `")
          .append(v.count().name())
          .append("` initialized,\n")
          .append(
              "    /// aligned elements that stay valid and unmodified for as long as the record")
          .append(" is borrowed,\n")
          .append("    /// and a null one has a zero count. Debug builds assert both rules.\n")
          .append("    #[inline]\n    pub fn ")
          .append(v.pointer().name())
          .append("(&self) -> &[")
          .append(element)
          .append("] {\n");
      out.append("        let count = ")
          .append(count)
          .append(" as usize;\n        if ")
          .append(pointer)
          .append(".is_null() {\n            debug_assert!(count == 0, \"")
          .append(v.label())
          .append(": null with a nonzero count\");\n")
          .append("            return &[];\n        }\n")
          .append("        debug_assert!(count <= isize::MAX as usize / core::mem::size_of::<")
          .append(element)
          .append(">(), \"")
          .append(v.label())
          .append(": count overflows isize\");\n")
          .append("        debug_assert!(")
          .append(pointer)
          .append(".is_aligned(), \"")
          .append(v.label())
          .append(": misaligned\");\n")
          .append("        // SAFETY: the record's contract above; null was handled.\n")
          .append("        unsafe { core::slice::from_raw_parts(")
          .append(pointer)
          .append(", count) }\n    }\n");
    }
    out.append("}\n");
  }

  public String generate(Module m) {
    var out =
        new StringBuilder(
            "// Generated by myna. Raw ABI; callers uphold ownership and contracts.\n");
    out.append("pub const ABI_FINGERPRINT: &str = ")
        .append(SeamJson.quote(SeamJson.fingerprint(m)))
        .append(";\n");
    out.append("pub const BINDING_ABI_VERSION: u32 = ")
        .append(Seam.BINDING_ABI_VERSION)
        .append(";\n");
    out.append("const _: () = assert!(core::mem::size_of::<*const ()>() == 8);\n");
    constants(m, out);
    for (String name : m.opaqueTypes())
      out.append("#[repr(C)]\npub struct ").append(name).append(" { _private: [u8; 0] }\n");
    for (Signature c : m.callbacks()) {
      out.append("pub type ")
          .append(c.name())
          .append(" = Option<unsafe extern \"C\" fn(")
          .append(String.join(", ", c.parameters().stream().map(Types::rust).toList()))
          .append(')');
      if (c.returns() != Scalar.VOID)
        out.append(" -> ").append(Types.rust(c.returns(), c.returnsGroup()));
      out.append(">;\n");
    }
    for (Struct s : m.structs()) {
      out.append("#[repr(C)]\n#[derive(Clone, Copy)]\npub struct ").append(s.name()).append(" {\n");
      long offset = 0;
      int padding = 0;
      for (Field f : s.fields()) {
        if (f.offset() > offset)
          out.append("    pub seamPadding")
              .append(padding++)
              .append(": [u8; ")
              .append(f.offset() - offset)
              .append("],\n");
        out.append("    pub ")
            .append(f.name())
            .append(": ")
            .append(Types.rust(f.type(), f.group()))
            .append(",\n");
        offset = f.offset() + Validator.size(f.type());
      }
      if (s.size() > offset)
        out.append("    pub seamPadding")
            .append(padding)
            .append(": [u8; ")
            .append(s.size() - offset)
            .append("],\n");
      out.append("}\nconst _: () = {\n    assert!(core::mem::size_of::<")
          .append(s.name())
          .append(">() == ")
          .append(s.size())
          .append(");\n");
      out.append("    assert!(core::mem::align_of::<")
          .append(s.name())
          .append(">() == ")
          .append(s.alignment())
          .append(");\n");
      for (Field f : s.fields())
        out.append("    assert!(core::mem::offset_of!(")
            .append(s.name())
            .append(", ")
            .append(f.name())
            .append(") == ")
            .append(f.offset())
            .append(");\n");
      out.append("};\n");
      views(m, s, out);
    }
    out.append("\nunsafe extern \"C\" {\n");
    for (Function declared : m.functions()) {
      // Native Image exports records by reference; a by-value wrapper follows the block.
      boolean wrapped = declared.direction() == Direction.EXPORT && ByValue.applies(declared);
      Function f = wrapped ? ByValue.lower(m, declared) : declared;
      out.append("    // ").append(f.direction()).append("; error=").append(f.error()).append('\n');
      for (Parameter p : f.abiParameters())
        out.append("    // ")
            .append(p.name())
            .append(": nullable=")
            .append(p.nullable())
            .append(" ownership=")
            .append(p.ownership())
            .append(" access=")
            .append(p.access())
            .append('\n');
      out.append("    #[link_name = ")
          .append(SeamJson.quote(f.symbol()))
          .append("]\n    pub fn ")
          .append(f.name())
          .append(wrapped ? "Ref" : "")
          .append('(');
      out.append(
              String.join(
                  ", ",
                  f.abiParameters().stream().map(p -> p.name() + ": " + Types.rust(p)).toList()))
          .append(')');
      if (f.returns() != Scalar.VOID)
        out.append(" -> ").append(Types.rust(f.returns(), f.returnsGroup()));
      out.append(";\n");
    }
    out.append("}\n");
    for (Function f : m.functions())
      if (f.direction() == Direction.EXPORT && ByValue.applies(f)) wrapper(m, f, out);
    // Function-pointer types for callers that resolve symbols dynamically (dlsym/GetProcAddress).
    for (Function declared : m.functions()) {
      Function f = declared.direction() == Direction.EXPORT ? ByValue.lower(m, declared) : declared;
      out.append("pub type ")
          .append(Character.toUpperCase(f.name().charAt(0)))
          .append(f.name().substring(1))
          .append("Fn = unsafe extern \"C\" fn(")
          .append(String.join(", ", f.abiParameters().stream().map(Types::rust).toList()))
          .append(')');
      if (f.returns() != Scalar.VOID)
        out.append(" -> ").append(Types.rust(f.returns(), f.returnsGroup()));
      out.append(";\n");
    }
    var imports = m.functions().stream().filter(f -> f.direction() == Direction.IMPORT).toList();
    if (!imports.isEmpty()) {
      out.append(
          "\n/// Pins each import's implementation, in scope under its symbol name, to this ABI.\n"
              + "/// Pass this module's path when the declared types are not in scope.\n"
              + "#[allow(unused_macros)]\nmacro_rules! assert_implementations {\n"
              + "    () => {\n        const _: () = {\n");
      pins(imports, "", out);
      out.append("        };\n    };\n    ($($seam:ident)::+) => {\n        const _: () = {\n");
      pins(imports, "$($seam)::+::", out);
      out.append(
          "        };\n"
              + "    };\n"
              + "}\n"
              + "#[allow(unused_imports)]\n"
              + "pub(crate) use assert_implementations;\n");
      var byValue = imports.stream().filter(ByValue::applies).toList();
      if (!byValue.isEmpty()) shims(m, byValue, out);
    }
    out.append(RustOwnership.generate(m));
    return out.toString();
  }

  private static void constants(Module m, StringBuilder out) {
    for (Constant c : m.constants())
      out.append("pub const ")
          .append(c.name().toUpperCase(Locale.ROOT))
          .append(": ")
          .append(Types.rust(c.type()))
          .append(" = ")
          .append(literal(c.type(), c.value(), c.type().text().startsWith("u")))
          .append(";\n");
    for (EnumGroup e : m.enums()) {
      String carrier = Types.rust(e.type());
      newtype(
          out,
          e.name(),
          carrier,
          "enum "
              + e.name()
              + ": "
              + carrier
              + ". Open set: every "
              + carrier
              + " is a valid `"
              + e.name()
              + "`; undeclared values equal no constant.");
      for (EnumValue v : e.values()) constant(out, v.name(), literal(e.type(), v.value(), false));
      out.append("    #[inline]\n    pub const fn name(self) -> Option<&'static str> {\n")
          .append("        match self.0 { ");
      for (EnumValue v : e.values())
        out.append(literal(e.type(), v.value(), false))
            .append(" => Some(")
            .append(SeamJson.quote(v.name()))
            .append("), ");
      out.append("_ => None }\n    }\n}\n");
    }
    for (FlagSet f : m.flagSets()) {
      String carrier = Types.rust(f.type());
      String n = f.name();
      newtype(out, n, carrier, "flags " + n + ": " + carrier + ".");
      constant(out, "NONE", "0");
      BigInteger all = BigInteger.ZERO;
      for (FlagBit b : f.bits()) {
        BigInteger mask = BigInteger.ONE.shiftLeft(b.bit());
        all = all.or(mask);
        constant(out, b.name(), literal(f.type(), mask, true));
      }
      constant(out, "ALL", literal(f.type(), all, true));
      out.append(
              "    #[inline(always)] pub const fn contains(self, other: Self) -> bool { self.0 &"
                  + " other.0 == other.0 }\n"
                  + "    #[inline(always)] pub const fn intersects(self, other: Self) -> bool {"
                  + " self.0 & other.0 != 0 }\n"
                  + "    #[inline(always)] pub const fn union(self, other: Self) -> Self {"
                  + " Self(self.0 | other.0) }\n"
                  + "    /// `self` if `on`, otherwise no bits. Written as a multiply so a single"
                  + " bit lowers to a shift.\n"
                  + "    #[inline(always)] pub const fn when(self, on: bool) -> Self { Self(self.0"
                  + " * on as ")
          .append(carrier)
          .append(") }\n}\n");
      for (String[] op : new String[][] {{"BitOr", "bitor", "|"}, {"BitAnd", "bitand", "&"}})
        out.append("impl core::ops::")
            .append(op[0])
            .append(" for ")
            .append(n)
            .append(" { type Output = Self; #[inline(always)] fn ")
            .append(op[1])
            .append("(self, o: Self) -> Self { Self(self.0 ")
            .append(op[2])
            .append(" o.0) } }\n");
    }
  }

  private static void newtype(StringBuilder out, String name, String carrier, String doc) {
    out.append("\n/// ")
        .append(doc)
        .append(
            "\n"
                + "#[repr(transparent)]\n"
                + "#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\n"
                + "pub struct ")
        .append(name)
        .append("(pub ")
        .append(carrier)
        .append(");\nimpl ")
        .append(name)
        .append(" {\n");
  }

  private static void constant(StringBuilder out, String name, String value) {
    out.append("    pub const ")
        .append(name.toUpperCase(Locale.ROOT))
        .append(": Self = Self(")
        .append(value)
        .append(");\n");
  }

  /** A literal in hex when {@code hex} (unsigned constants, flag masks), else decimal. */
  static String literal(Scalar type, BigInteger value, boolean hex) {
    int bits = type == Scalar.USIZE || type == Scalar.ISIZE ? 64 : type.bytes * 8;
    boolean unsigned = type.text().startsWith("u");
    // A signed mask with the sign bit set is that bit pattern's negative value; a hex literal
    // would not fit the type.
    if (!unsigned && hex && value.bitLength() >= bits)
      value = value.subtract(BigInteger.ONE.shiftLeft(bits));
    else if (hex) return "0x" + value.toString(16);
    return value.toString();
  }

  private static void pins(java.util.List<Function> imports, String q, StringBuilder out) {
    for (Function f : imports) {
      out.append("            let _: unsafe extern \"C\" fn(")
          .append(String.join(", ", f.abiParameters().stream().map(p -> Types.rust(p, q)).toList()))
          .append(')');
      if (f.returns() != Scalar.VOID)
        out.append(" -> ").append(Types.rust(f.returns(), f.returnsGroup(), q));
      out.append(" = ").append(f.symbol()).append(";\n");
    }
  }

  /** Inline by-value wrapper over a Native Image export's reference form. */
  private static void wrapper(Module m, Function f, StringBuilder out) {
    out.append("#[inline]\n#[allow(non_snake_case, clippy::missing_safety_doc)]\npub unsafe fn ")
        .append(f.name())
        .append('(')
        .append(
            String.join(
                ", ",
                f.abiParameters().stream().map(p -> p.name() + ": " + Types.rust(p)).toList()))
        .append(')');
    if (f.returns() != Scalar.VOID)
      out.append(" -> ").append(Types.rust(f.returns(), f.returnsGroup()));
    out.append(" {\n");
    boolean record = f.returns() instanceof Named;
    if (record)
      out.append("    let mut result = core::mem::MaybeUninit::<")
          .append(Types.rust(f.returns()))
          .append(">::uninit();\n");
    var args = new java.util.ArrayList<String>();
    for (Parameter p : f.abiParameters())
      args.add(p.type() instanceof Named ? "&" + p.name() : p.name());
    if (record) args.add("result.as_mut_ptr()");
    out.append("    unsafe { ")
        .append(f.name())
        .append("Ref(")
        .append(String.join(", ", args))
        .append(") }");
    out.append(record ? ";\n    unsafe { result.assume_init() }\n}\n" : "\n}\n");
  }

  /**
   * Reference-form definitions for by-value imports, for the crate that implements them and links
   * into Native Image. Each reads its records and calls the implementation by symbol name.
   */
  private static void shims(Module m, java.util.List<Function> imports, StringBuilder out) {
    String q = "$($seam)::+::";
    out.append(
        "\n/// Defines the Native Image reference forms of by-value imports beside their\n"
            + "/// implementations; pass this module's path.\n"
            + "#[allow(unused_macros)]\nmacro_rules! native_image_shims {\n"
            + "    ($($seam:ident)::+) => {\n");
    for (Function f : imports) {
      Function ref = ByValue.lower(m, f);
      out.append("        #[unsafe(no_mangle)]\n        #[allow(non_snake_case)]\n")
          .append("        pub unsafe extern \"C\" fn ")
          .append(ref.symbol())
          .append('(')
          .append(
              String.join(
                  ", ",
                  ref.parameters().stream().map(p -> p.name() + ": " + Types.rust(p, q)).toList()))
          .append(')');
      if (ref.returns() != Scalar.VOID)
        out.append(" -> ").append(Types.rust(ref.returns(), ref.returnsGroup(), q));
      String call =
          f.symbol()
              + "("
              + String.join(
                  ", ",
                  f.parameters().stream()
                      .map(p -> p.type() instanceof Named ? p.name() + ".read()" : p.name())
                      .toList())
              + ")";
      out.append(" {\n            unsafe { ")
          .append(f.returns() instanceof Named ? ByValue.RESULT + ".write(" + call + ")" : call)
          .append(" }\n        }\n");
    }
    out.append("    };\n}\n#[allow(unused_imports)]\npub(crate) use native_image_shims;\n");
  }
}
