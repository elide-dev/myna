package dev.elide.myna.backend;

import dev.elide.myna.model.Names;
import dev.elide.myna.model.Seam;
import dev.elide.myna.model.Seam.*;
import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.Fingerprint;
import dev.elide.myna.serialize.SeamJson;
import dev.elide.myna.validate.Validator;
import java.math.BigInteger;
import java.util.*;

public final class CHeader implements Backend {
  public String filename(Module module) {
    return "seam.h";
  }

  public String generate(Module m) {
    return generate(m, new Fingerprint(m));
  }

  public String generate(Module m, Fingerprint abi) {
    return header(m, abi).text();
  }

  /**
   * A generated {@code seam.h} and the module instance it was generated for. Only {@link CHeader}
   * makes one, so {@link NativeImageDirectives#withHeader} can embed it knowing it is that module's
   * header.
   */
  public static final class Generated {
    private final Module module;
    private final String text;
    private final String queryText;

    private Generated(Module module, String text, String queryText) {
      this.module = module;
      this.text = text;
      this.queryText = queryText;
    }

    public String text() {
      return text;
    }

    String queryText() {
      return queryText;
    }

    /** Throws unless this header was generated for exactly {@code m}. */
    void requireFor(Module m) {
      if (m != module)
        throw new IllegalArgumentException(
            "seam.h of module "
                + module.name()
                + " ("
                + module.targetTriple()
                + ") used for another module instance");
    }
  }

  /** {@code seam.h} for {@code m}, which {@code abi} must describe. */
  public Generated header(Module m, Fingerprint abi) {
    String fingerprint = abi.valueFor(m);
    String guard = m.name().toUpperCase(Locale.ROOT) + "_SEAM_H";
    var out =
        new StringBuilder(
            "/* Generated by myna. ABI: "
                + fingerprint
                + " */\n#ifndef "
                + guard
                + "\n#define "
                + guard
                + "\n"
                + "#include <stdbool.h>\n"
                + "#include <stdint.h>\n"
                + "#include <stddef.h>\n\n"
                + "#ifdef __cplusplus\n"
                + "#define SEAM_ASSERT static_assert\n"
                + "#define SEAM_ALIGNOF alignof\n"
                + "extern \"C\" {\n"
                + "#elif defined(_MSC_VER) && (!defined(__STDC_VERSION__) || __STDC_VERSION__ <"
                + " 201112L)\n"
                + "#define SEAM_ASSERT_JOIN_(a, b) a##b\n"
                + "#define SEAM_ASSERT_JOIN(a, b) SEAM_ASSERT_JOIN_(a, b)\n"
                + "#define SEAM_ASSERT(c, m) typedef char SEAM_ASSERT_JOIN(seam_assert_,"
                + " __COUNTER__)[(c) ? 1 : -1]\n"
                + "#define SEAM_ALIGNOF __alignof\n"
                + "#else\n"
                + "#define SEAM_ASSERT _Static_assert\n"
                + "#define SEAM_ALIGNOF _Alignof\n"
                + "#endif\n\n");
    out.append("#define ")
        .append(m.name().toUpperCase(Locale.ROOT))
        .append("_SEAM_ABI ")
        .append(SeamJson.quote(fingerprint))
        .append('\n');
    // Defined only by this generation's header; the Native Image class reads it with @CConstant.
    out.append("#define ").append(Names.seamAbiCheck(m, fingerprint)).append(" 1\n");
    out.append("#define ")
        .append(m.name().toUpperCase(Locale.ROOT))
        .append("_BINDING_ABI_VERSION ")
        .append(Seam.BINDING_ABI_VERSION)
        .append('\n');
    out.append("SEAM_ASSERT(sizeof(void *) == 8, \"seam target requires 64-bit pointers\");\n\n");
    int abiStart = out.length();
    abiVersion(m, out);
    int abiEnd = out.length();
    constants(m, out);
    for (String name : m.opaqueTypes()) out.append("struct ").append(name).append(";\n");
    for (Struct s : m.structs()) out.append("struct ").append(s.name()).append(";\n");
    for (Signature c : m.callbacksInDependencyOrder())
      out.append("typedef ")
          .append(Types.c(m, c.returns(), c.returnsGroup()))
          .append(" (*")
          .append(c.name())
          .append(")(")
          .append(
              c.parameters().isEmpty()
                  ? "void"
                  : String.join(
                      ", ",
                      c.parameters().stream().map(p -> Types.c(m, p) + " " + p.name()).toList()))
          .append(");\n");
    for (Struct s : m.structs()) {
      out.append("struct ").append(s.name()).append(" {\n");
      long offset = 0;
      int padding = 0;
      for (Field f : s.fields()) {
        if (f.offset() > offset)
          out.append("  uint8_t seamPadding")
              .append(padding++)
              .append('[')
              .append(f.offset() - offset)
              .append("];\n");
        if (f.group() != null && f.group().kind() == GroupKind.FLAGS && bitfields(m, f.group())) {
          String carrier = Types.c(m, f.type(), f.group());
          out.append("  union {\n    ")
              .append(carrier)
              .append(' ')
              .append(f.name())
              .append(";\n    struct ")
              .append(Names.cBitsStruct(m, f.group().name()))
              .append(' ')
              .append(f.name())
              .append("Bits;\n  };\n");
        } else
          out.append("  ")
              .append(Types.c(m, f.type(), m.fieldTypeGroup(f)))
              .append(' ')
              .append(f.name())
              .append(";\n");
        offset = f.offset() + Validator.size(f.type());
      }
      if (s.size() > offset)
        out.append("  uint8_t seamPadding")
            .append(padding)
            .append('[')
            .append(s.size() - offset)
            .append("];\n");
      out.append("};\nSEAM_ASSERT(sizeof(struct ")
          .append(s.name())
          .append(") == ")
          .append(s.size())
          .append(", \"struct size\");\n");
      out.append("SEAM_ASSERT(SEAM_ALIGNOF(struct ")
          .append(s.name())
          .append(") == ")
          .append(s.alignment())
          .append(", \"struct alignment\");\n");
      for (Field f : s.fields())
        out.append("SEAM_ASSERT(offsetof(struct ")
            .append(s.name())
            .append(", ")
            .append(f.name())
            .append(") == ")
            .append(f.offset())
            .append(", \"field offset\");\n");
    }
    int prototypes = out.length();
    for (Function declared : m.functions()) {
      // Native Image lowers records by reference at its C boundary, so a by-value record import
      // has two C symbols: the by-value implementation (declared here, called by C/Rust/FFM) and
      // the reference form `<symbol>_myna_ref` (declared below, bound by Native Image). The C
      // provider must also define the latter — the C counterpart of `native_image_shims!` in
      // seam.rs. Exports invert this: the binding is the prototype and the by-value form is a
      // `static inline` wrapper.
      boolean byValue = ByValue.applies(declared);
      boolean wrapped = declared.direction() == Direction.EXPORT && byValue;
      boolean importRef = declared.direction() == Direction.IMPORT && byValue;
      Function lowered = (wrapped || importRef) ? ByValue.lower(m, declared) : declared;
      Function header = importRef ? declared : lowered;
      out.append("\n/* ")
          .append(header.direction())
          .append("; error=")
          .append(header.error())
          .append(
              header.returnsGroup() == null
                  ? ""
                  : "; returns "
                      + header.returnsGroup().kind().name().toLowerCase(Locale.ROOT)
                      + " "
                      + header.returnsGroup().name())
          .append(" */\n");
      for (Parameter p : header.abiParameters())
        out.append("/* ")
            .append(p.name())
            .append(": nullable=")
            .append(p.nullable())
            .append(" ownership=")
            .append(p.ownership())
            .append(" access=")
            .append(p.access())
            .append(" */\n");
      out.append(Types.c(m, header.returns(), header.returnsGroup()))
          .append(' ')
          .append(header.symbol())
          .append('(');
      out.append(
          header.abiParameters().isEmpty()
              ? "void"
              : String.join(
                  ", ",
                  header.abiParameters().stream()
                      .map(p -> Types.c(m, p) + " " + p.name())
                      .toList()));
      out.append(");\n");
      if (wrapped) wrapper(m, declared, lowered, out);
      if (importRef) importReference(m, lowered, out);
    }
    int footer = out.length();
    String text =
        out.append(
                "\n"
                    + "#ifdef __cplusplus\n"
                    + "}\n"
                    + "#endif\n"
                    + "#undef SEAM_ASSERT_JOIN\n"
                    + "#undef SEAM_ASSERT_JOIN_\n"
                    + "#undef SEAM_ASSERT\n"
                    + "#undef SEAM_ALIGNOF\n"
                    + "#endif\n")
            .toString();
    // The consumer may already declare its library functions and its own ABI version.
    String queryText =
        m.nativeConfig() != null && m.nativeConfig().cContext() != null
            ? text.substring(0, abiStart)
                + text.substring(abiEnd, prototypes)
                + text.substring(footer)
            : text;
    return new Generated(m, text, queryText);
  }

  private static boolean bitfields(Module m, GroupRef ref) {
    return m.flagSets().stream().anyMatch(f -> f.name().equals(ref.name()) && f.cBitfields());
  }

  private static void abiVersion(Module m, StringBuilder out) {
    if (m.abiDeclared()) {
      out.append("/* module abi=").append(m.abiVersion()).append(": i32 */\n");
      define(
          out,
          Names.abiVersionMacro(m),
          literal(Scalar.I32, BigInteger.valueOf(m.abiVersion()), false));
    }
  }

  private static void constants(Module m, StringBuilder out) {
    for (Constant c : m.constants()) {
      out.append("/* const ").append(c.name()).append(": ").append(c.type().text()).append(" */\n");
      define(
          out,
          Names.cMacro(m, null, c.name()),
          literal(c.type(), c.value(), c.type().text().startsWith("u")));
    }
    for (EnumGroup e : m.enums()) {
      String typedef = Names.cTypedef(m, e.name());
      String carrier = Types.c(e.type());
      out.append("/* enum ").append(e.name()).append(": ").append(e.type().text()).append(" */\n");
      out.append("typedef ").append(carrier).append(' ').append(typedef).append(";\n");
      for (EnumValue v : e.values())
        define(out, Names.cMacro(m, e.name(), v.name()), literal(e.type(), v.value(), false));
      out.append("static inline const char *")
          .append(Names.cNameFunction(m, e.name()))
          .append('(')
          .append(carrier)
          .append(" value) {\n  switch (value) {\n");
      for (EnumValue v : e.values()) // the validator rejects duplicate numbers
      out.append("    case ")
            .append(Names.cMacro(m, e.name(), v.name()))
            .append(": return ")
            .append(SeamJson.quote(v.name()))
            .append(";\n");
      out.append("    default: return NULL;\n  }\n}\n");
    }
    for (FlagSet f : m.flagSets()) {
      String carrier = Types.c(f.type());
      out.append("/* flags ").append(f.name()).append(": ").append(f.type().text()).append(" */\n");
      out.append("typedef ")
          .append(carrier)
          .append(' ')
          .append(Names.cTypedef(m, f.name()))
          .append(";\n");
      for (FlagBit b : f.bits())
        define(
            out,
            Names.cMacro(m, f.name(), b.name()),
            literal(f.type(), BigInteger.ONE.shiftLeft(b.bit()), true));
      for (FlagRange r : f.ranges()) {
        define(
            out,
            Names.cMacro(m, f.name(), r.name() + "_width"),
            literal(f.type(), BigInteger.valueOf(r.width()), false));
        define(
            out,
            Names.cMacro(m, f.name(), r.name() + "_shift"),
            literal(f.type(), BigInteger.valueOf(r.low()), false));
        define(
            out, Names.cMacro(m, f.name(), r.name() + "_mask"), literal(f.type(), r.mask(), true));
      }
      define(out, Names.cMacro(m, f.name(), "ALL"), literal(f.type(), f.all(), true));
      for (FlagRange r : f.ranges()) rangeFunctions(m, f, r, out);
      if (f.cBitfields()) bitsStruct(m, f, carrier, out);
    }
    if (m.declaresConstants()) out.append('\n');
  }

  /**
   * A range's getter and setter: pure functions of the word, computed on the unsigned carrier so a
   * signed word's sign bit is an ordinary bit. The setter masks the value to the range's width.
   */
  private static void rangeFunctions(Module m, FlagSet f, FlagRange r, StringBuilder out) {
    String word = Names.cTypedef(m, f.name());
    String value = r.enumName() == null ? word : Names.cTypedef(m, r.enumName());
    String unsigned = "uint" + (f.type().bytes * 8) + "_t";
    String shift = Names.cMacro(m, f.name(), r.name() + "_shift");
    String mask = Names.cMacro(m, f.name(), r.name() + "_mask");
    out.append("static inline ")
        .append(value)
        .append(' ')
        .append(Names.cFlagFunction(m, f.name(), r.name()))
        .append('(')
        .append(word)
        .append(" flags) {\n  return (")
        .append(value)
        .append(")(((")
        .append(unsigned)
        .append(")flags & (")
        .append(unsigned)
        .append(")")
        .append(mask)
        .append(") >> ")
        .append(shift)
        .append(");\n}\n");
    out.append("static inline ")
        .append(word)
        .append(' ')
        .append(Names.cFlagFunction(m, f.name(), "with_" + r.name()))
        .append('(')
        .append(word)
        .append(" flags, ")
        .append(value)
        .append(" value) {\n  return (")
        .append(word)
        .append(")(((")
        .append(unsigned)
        .append(")flags & (")
        .append(unsigned)
        .append(")~(")
        .append(unsigned)
        .append(")")
        .append(mask)
        .append(") | (((")
        .append(unsigned)
        .append(")value << ")
        .append(shift)
        .append(") & (")
        .append(unsigned)
        .append(")")
        .append(mask)
        .append("));\n}\n");
  }

  /** LSB-first bit-fields; unnamed gaps keep each bit and range at its index. */
  private static void bitsStruct(Module m, FlagSet f, String carrier, StringBuilder out) {
    String name = Names.cBitsStruct(m, f.name());
    out.append("struct ").append(name).append(" {\n");
    var members = new TreeMap<Integer, String[]>();
    for (FlagBit b : f.bits()) members.put(b.bit(), new String[] {b.name(), "1"});
    for (FlagRange r : f.ranges())
      members.put(r.low(), new String[] {r.name(), Integer.toString(r.width())});
    int next = 0;
    for (var member : members.entrySet()) {
      int low = member.getKey(), width = Integer.parseInt(member.getValue()[1]);
      if (low > next)
        out.append("  ").append(carrier).append(" : ").append(low - next).append(";\n");
      out.append("  ")
          .append(carrier)
          .append(' ')
          .append(member.getValue()[0])
          .append(" : ")
          .append(width)
          .append(";\n");
      next = low + width;
    }
    out.append("};\nSEAM_ASSERT(sizeof(struct ")
        .append(name)
        .append(") == sizeof(")
        .append(carrier)
        .append("), \"bit-field struct size\");\n");
  }

  private static void define(StringBuilder out, String macro, String value) {
    out.append("#define ").append(macro).append(' ').append(value).append('\n');
  }

  /**
   * A typed integer literal in hex when {@code hex} (unsigned constants, flag masks), else decimal.
   */
  static String literal(Scalar type, BigInteger value, boolean hex) {
    int bits = type == Scalar.USIZE || type == Scalar.ISIZE ? 64 : type.bytes * 8;
    boolean unsigned = type.text().startsWith("u");
    if (unsigned)
      return "UINT" + bits + "_C(" + (hex ? "0x" + value.toString(16) : value.toString()) + ")";
    // A signed mask with the sign bit set is that bit pattern's negative value, not a hex literal
    // (which would not fit the type).
    if (hex && value.bitLength() >= bits) value = value.subtract(BigInteger.ONE.shiftLeft(bits));
    else if (hex) return "INT" + bits + "_C(0x" + value.toString(16) + ")";
    String macro = "INT" + bits + "_C";
    BigInteger min = BigInteger.ONE.shiftLeft(bits - 1).negate();
    if (value.equals(min))
      return "(-" + macro + "(" + min.negate().subtract(BigInteger.ONE) + ") - 1)";
    return value.signum() < 0 ? "(" + macro + "(" + value + "))" : macro + "(" + value + ")";
  }

  /**
   * Declares the Native Image reference form of a by-value record import, alongside its by-value
   * prototype above. The C provider supplies both definitions: the by-value {@code
   * declared.symbol()} called by C/Rust/FFM, and the {@code _myna_ref} reference form bound by
   * Native Image. This mirrors the export treatment (which emits the reference prototype and a
   * {@code static inline} by-value wrapper) and keeps {@code seam.h} consistent with {@code
   * seam.rs} ({@code native_image_shims!}), {@code seam.ll} (which declares only the reference
   * form), and the Native Image backend's symbol expectations.
   */
  private static void importReference(Module m, Function lowered, StringBuilder out) {
    out.append("/* Native Image binds ")
        .append(lowered.symbol())
        .append(
            "; the C provider must also define it (the C counterpart of"
                + " `native_image_shims!`). */\n");
    out.append(Types.c(m, lowered.returns(), lowered.returnsGroup()))
        .append(' ')
        .append(lowered.symbol())
        .append('(');
    out.append(
        String.join(
            ", ",
            lowered.abiParameters().stream().map(p -> Types.c(m, p) + " " + p.name()).toList()));
    out.append(");\n");
  }

  private static void wrapper(Module m, Function f, Function ref, StringBuilder out) {
    boolean record = f.returns() instanceof Named;
    out.append("static inline ")
        .append(Types.c(m, f.returns(), f.returnsGroup()))
        .append(' ')
        .append(f.symbol())
        .append('(')
        .append(
            String.join(
                ", ", f.abiParameters().stream().map(p -> Types.c(m, p) + " " + p.name()).toList()))
        .append(") {\n");
    if (record)
      out.append("  ").append(Types.c(m, f.returns(), f.returnsGroup())).append(" result;\n");
    var args = new java.util.ArrayList<String>();
    for (Parameter p : f.abiParameters())
      args.add(p.type() instanceof Named ? "&" + p.name() : p.name());
    if (record) args.add("&result");
    out.append("  ")
        .append(!record && f.returns() != Scalar.VOID ? "return " : "")
        .append(ref.symbol())
        .append('(')
        .append(String.join(", ", args))
        .append(");\n")
        .append(record ? "  return result;\n" : "")
        .append("}\n");
  }
}
