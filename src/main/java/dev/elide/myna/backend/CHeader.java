package dev.elide.myna.backend;

import dev.elide.myna.model.Seam;
import dev.elide.myna.model.Seam.*;
import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.SeamJson;
import dev.elide.myna.validate.Validator;
import java.util.*;

public final class CHeader implements Backend {
  public String filename(Module module) {
    return "seam.h";
  }

  public String generate(Module m) {
    String guard = m.name().toUpperCase(Locale.ROOT) + "_SEAM_H";
    String fingerprint = SeamJson.fingerprint(m);
    var out =
        new StringBuilder(
            "/* Generated by myna. ABI: "
                + fingerprint
                + " */\n#ifndef "
                + guard
                + "\n#define "
                + guard
                + "\n"
                + "#include <stdbool.h>\n"
                + "#include <stdint.h>\n"
                + "#include <stddef.h>\n\n"
                + "#ifdef __cplusplus\n"
                + "#define SEAM_ASSERT static_assert\n"
                + "#define SEAM_ALIGNOF alignof\n"
                + "extern \"C\" {\n"
                + "#else\n"
                + "#define SEAM_ASSERT _Static_assert\n"
                + "#define SEAM_ALIGNOF _Alignof\n"
                + "#endif\n\n");
    out.append("#define ")
        .append(m.name().toUpperCase(Locale.ROOT))
        .append("_SEAM_ABI ")
        .append(SeamJson.quote(fingerprint))
        .append('\n');
    out.append("#define ")
        .append(m.name().toUpperCase(Locale.ROOT))
        .append("_BINDING_ABI_VERSION ")
        .append(Seam.BINDING_ABI_VERSION)
        .append('\n');
    out.append("SEAM_ASSERT(sizeof(void *) == 8, \"seam target requires 64-bit pointers\");\n\n");
    for (String name : m.opaqueTypes()) out.append("struct ").append(name).append(";\n");
    for (Struct s : m.structs()) out.append("struct ").append(s.name()).append(";\n");
    for (Signature c : m.callbacks())
      out.append("typedef ")
          .append(Types.c(c.returns()))
          .append(" (*")
          .append(c.name())
          .append(")(")
          .append(
              c.parameters().isEmpty()
                  ? "void"
                  : String.join(
                      ", ", c.parameters().stream().map(p -> Types.c(p) + " " + p.name()).toList()))
          .append(");\n");
    for (Struct s : m.structs()) {
      out.append("struct ").append(s.name()).append(" {\n");
      long offset = 0;
      int padding = 0;
      for (Field f : s.fields()) {
        if (f.offset() > offset)
          out.append("  uint8_t seamPadding")
              .append(padding++)
              .append('[')
              .append(f.offset() - offset)
              .append("];\n");
        out.append("  ").append(Types.c(f.type())).append(' ').append(f.name()).append(";\n");
        offset = f.offset() + Validator.size(f.type());
      }
      if (s.size() > offset)
        out.append("  uint8_t seamPadding")
            .append(padding)
            .append('[')
            .append(s.size() - offset)
            .append("];\n");
      out.append("};\nSEAM_ASSERT(sizeof(struct ")
          .append(s.name())
          .append(") == ")
          .append(s.size())
          .append(", \"struct size\");\n");
      out.append("SEAM_ASSERT(SEAM_ALIGNOF(struct ")
          .append(s.name())
          .append(") == ")
          .append(s.alignment())
          .append(", \"struct alignment\");\n");
      for (Field f : s.fields())
        out.append("SEAM_ASSERT(offsetof(struct ")
            .append(s.name())
            .append(", ")
            .append(f.name())
            .append(") == ")
            .append(f.offset())
            .append(", \"field offset\");\n");
    }
    for (Function declared : m.functions()) {
      // Native Image lowers records by reference at its C boundary, so a by-value record import
      // has two C symbols: the by-value implementation (declared here, called by C/Rust/FFM) and
      // the reference form `<symbol>_myna_ref` (declared below, bound by Native Image). The C
      // provider must also define the latter — the C counterpart of `native_image_shims!` in
      // seam.rs. Exports invert this: the binding is the prototype and the by-value form is a
      // `static inline` wrapper.
      boolean byValue = ByValue.applies(declared);
      boolean wrapped = declared.direction() == Direction.EXPORT && byValue;
      boolean importRef = declared.direction() == Direction.IMPORT && byValue;
      Function lowered = (wrapped || importRef) ? ByValue.lower(m, declared) : declared;
      Function header = importRef ? declared : lowered;
      out.append("\n/* ")
          .append(header.direction())
          .append("; error=")
          .append(header.error())
          .append(" */\n");
      for (Parameter p : header.abiParameters())
        out.append("/* ")
            .append(p.name())
            .append(": nullable=")
            .append(p.nullable())
            .append(" ownership=")
            .append(p.ownership())
            .append(" access=")
            .append(p.access())
            .append(" */\n");
      out.append(Types.c(header.returns())).append(' ').append(header.symbol()).append('(');
      out.append(
          header.abiParameters().isEmpty()
              ? "void"
              : String.join(
                  ", ",
                  header.abiParameters().stream().map(p -> Types.c(p) + " " + p.name()).toList()));
      out.append(");\n");
      if (wrapped) wrapper(declared, lowered, out);
      if (importRef) importReference(lowered, out);
    }
    return out.append(
            "\n#ifdef __cplusplus\n}\n#endif\n#undef SEAM_ASSERT\n#undef SEAM_ALIGNOF\n#endif\n")
        .toString();
  }

  /**
   * Declares the Native Image reference form of a by-value record import, alongside its by-value
   * prototype above. The C provider supplies both definitions: the by-value {@code
   * declared.symbol()} called by C/Rust/FFM, and the {@code _myna_ref} reference form bound by
   * Native Image. This mirrors the export treatment (which emits the reference prototype and a
   * {@code static inline} by-value wrapper) and keeps {@code seam.h} consistent with {@code
   * seam.rs} ({@code native_image_shims!}), {@code seam.ll} (which declares only the reference
   * form), and the Native Image backend's symbol expectations.
   */
  private static void importReference(Function lowered, StringBuilder out) {
    out.append("/* Native Image binds ")
        .append(lowered.symbol())
        .append(
            "; the C provider must also define it (the C counterpart of"
                + " `native_image_shims!`). */\n");
    out.append(Types.c(lowered.returns())).append(' ').append(lowered.symbol()).append('(');
    out.append(
        lowered.abiParameters().isEmpty()
            ? "void"
            : String.join(
                ", ",
                lowered.abiParameters().stream().map(p -> Types.c(p) + " " + p.name()).toList()));
    out.append(");\n");
  }

  private static void wrapper(Function f, Function ref, StringBuilder out) {
    boolean record = f.returns() instanceof Named;
    out.append("static inline ")
        .append(Types.c(f.returns()))
        .append(' ')
        .append(f.symbol())
        .append('(')
        .append(
            String.join(
                ", ", f.abiParameters().stream().map(p -> Types.c(p) + " " + p.name()).toList()))
        .append(") {\n");
    if (record) out.append("  ").append(Types.c(f.returns())).append(" result;\n");
    var args = new java.util.ArrayList<String>();
    for (Parameter p : f.abiParameters())
      args.add(p.type() instanceof Named ? "&" + p.name() : p.name());
    if (record) args.add("&result");
    out.append("  ")
        .append(!record && f.returns() != Scalar.VOID ? "return " : "")
        .append(ref.symbol())
        .append('(')
        .append(String.join(", ", args))
        .append(");\n")
        .append(record ? "  return result;\n" : "")
        .append("}\n");
  }
}
