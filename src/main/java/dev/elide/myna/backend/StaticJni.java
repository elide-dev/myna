package dev.elide.myna.backend;

import dev.elide.myna.model.Seam.*;
import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.SeamJson;
import java.util.*;

/** Optional SVM JNI adapter: a real JNIEnv/jclass wrapper delegates to the raw C seam. */
public final class StaticJni {
  private StaticJni() {}

  public static Map<String, String> generate(Module m) {
    var methods = JniAbi.methods(m);
    if (methods.isEmpty()) throw new IllegalArgumentException("JNI generation requires imports");
    String cls = JniAbi.className(m);
    var java =
        new StringBuilder(
                "// Generated by myna. Raw address methods require caller-managed lifetimes.\n"
                    + "package ")
            .append(m.javaPackageName())
            .append(";\n\npublic final class ")
            .append(cls)
            .append(" {\n    private ")
            .append(cls)
            .append("() {}\n")
            .append("    public static final String ABI_FINGERPRINT = ")
            .append(SeamJson.quote(SeamJson.fingerprint(m)))
            .append(";\n")
            .append("    static { System.loadLibrary(")
            .append(SeamJson.quote(JniAbi.library(m)))
            .append("); }\n");
    var c =
        new StringBuilder(
                "/* Generated by myna. JNI adapter facts are distinct from raw C facts. */\n")
            .append("#include \"seam-jni.h\"\n#include \"seam.h\"\n\n")
            .append("JNIEXPORT jint JNICALL JNI_OnLoad_")
            .append(JniAbi.library(m))
            .append(
                "(JavaVM *vm, void *reserved) {\n"
                    + "  (void)vm; (void)reserved; return JNI_VERSION_1_8;\n"
                    + "}\n");
    var llvm =
        new StringBuilder(new Llvm().generate(m))
            .append("\n; JNI signatures: no raw function effects propagate to wrappers.\n");
    var header =
        new StringBuilder(
                "/* Generated JNI ABI. Handles are valid only with their owning JNIEnv. */\n")
            .append("#include <jni.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
    var rust =
        new StringBuilder(
                "// Generated JNI ABI. JNI references are handles, not raw seam pointers.\n")
            .append("unsafe extern \"C\" {\n");
    for (JniAbi.Method method : methods) {
      header
          .append("JNIEXPORT ")
          .append(method.returns().c())
          .append(" JNICALL ")
          .append(method.symbol())
          .append('(')
          .append(
              String.join(
                  ", ",
                  method.arguments().stream().map(a -> a.carrier().c() + " " + a.name()).toList()))
          .append(");\n");
      rust.append("    pub fn ")
          .append(method.symbol())
          .append('(')
          .append(
              String.join(
                  ", ",
                  method.arguments().stream()
                      .map(a -> a.name() + ": " + a.carrier().rust())
                      .toList()))
          .append(") -> ")
          .append(method.returns().rust())
          .append(";\n");
      java.append("    ")
          .append(method.borrows().isEmpty() ? "public" : "private")
          .append(" static native ")
          .append(method.returns().java())
          .append(' ')
          .append(method.name())
          .append('(')
          .append(
              String.join(
                  ", ",
                  method.arguments().stream()
                      .skip(2)
                      .map(a -> a.carrier().java() + " " + a.name())
                      .toList()))
          .append(");\n");
      if (!method.borrows().isEmpty()) bufferJava(method, java);
      c.append("JNIEXPORT ")
          .append(method.returns().c())
          .append(" JNICALL ")
          .append(method.symbol())
          .append('(')
          .append(
              String.join(
                  ", ",
                  method.arguments().stream()
                      .map(a -> a.carrier().c() + " " + cName(method, a.name()))
                      .toList()))
          .append(") {\n  (void)")
          .append(cName(method, "clazz"))
          .append(";\n")
          .append("  if ((*")
          .append(cName(method, "env"))
          .append(")->ExceptionCheck(")
          .append(cName(method, "env"))
          .append(")) return")
          .append(method.returns().java().equals("void") ? "" : " 0")
          .append(";\n");
      call(method, c);
      c.append("}\n");
      llvm.append("declare ")
          .append(method.returns().llvm())
          .append(" @")
          .append(method.symbol())
          .append('(')
          .append(
              String.join(
                  ", ",
                  method.arguments().stream()
                      .map(a -> a.carrier().llvmArgument(m.targetTriple()) + " %" + a.name())
                      .toList()))
          .append(")\n");
    }
    java.append("}\n");
    header.append("#ifdef __cplusplus\n}\n#endif\n");
    rust.append("}\n");
    return Map.of(
        cls + ".java",
        java.toString(),
        "seam-jni.c",
        c.toString(),
        "seam-jni.ll",
        llvm.toString(),
        "seam-jni.h",
        header.toString(),
        "seam-jni.rs",
        rust.toString(),
        "lib" + JniAbi.library(m) + ".a.symbols",
        "JNI_OnLoad_"
            + JniAbi.library(m)
            + "\n"
            + String.join("\n", methods.stream().map(JniAbi.Method::symbol).toList())
            + "\n",
        "META-INF/native-image/dev.elide.myna/"
            + m.javaPackageName()
            + "."
            + cls
            + "/native-image.properties",
        "# SVM discovers the literal System.loadLibrary call and links the JNI archive.\n"
            + "Args = -H:+UnlockExperimentalVMOptions -H:JNILibraryLinkage="
            + JniAbi.library(m)
            + ":static? -H:-UnlockExperimentalVMOptions --initialize-at-run-time="
            + m.javaPackageName()
            + "."
            + cls
            + "\n");
  }

  /** Distinguishes one buffer's locals: nothing for a method's only buffer, else its position. */
  private static String suffix(JniAbi.Method method, int position) {
    return method.borrows().size() == 1 ? "" : String.valueOf(position);
  }

  private static void bufferJava(JniAbi.Method method, StringBuilder out) {
    boolean several = method.borrows().size() > 1;
    var args = new ArrayList<String>();
    var checks = new StringBuilder();
    int index = 0;
    for (Parameter p : method.implementation().abiParameters()) {
      String name = "arg" + index;
      String segment = "segment" + suffix(method, index++);
      if (method.length(p)) continue;
      if (!method.buffer(p)) {
        args.add(name);
        continue;
      }
      // A null ByteBuffer for a nullable buffer is an absent one: nothing to check or slice.
      boolean nullable = p.nullable();
      String pad = nullable ? "            " : "        ";
      args.add(nullable ? name + " == null ? null : " + name + ".slice()" : name + ".slice()");
      if (nullable) checks.append("        if (").append(name).append(" != null) {\n");
      checks
          .append(pad)
          .append("if (!")
          .append(name)
          .append(".isDirect()) throw new IllegalArgumentException(\"direct buffer required\");\n");
      if (p.access() != Access.READ)
        checks
            .append(pad)
            .append("if (")
            .append(name)
            .append(
                ".isReadOnly()) throw new IllegalArgumentException(\"writable buffer"
                    + " required\");\n");
      checks
          .append(pad)
          .append("java.lang.foreign.MemorySegment ")
          .append(segment)
          .append(" = java.lang.foreign.MemorySegment.ofBuffer(")
          .append(name)
          .append(");\n")
          .append(pad)
          .append("if (!")
          .append(segment)
          .append(".scope().isAlive()) throw new IllegalStateException(\"closed buffer\");\n")
          .append(pad)
          .append("if (!")
          .append(segment)
          .append(".isAccessibleBy(Thread.currentThread())) throw new WrongThreadException();\n");
      if (nullable) checks.append("        }\n");
    }
    out.append(
            several
                ? "    /** Borrows remaining bytes of each direct buffer; preserves their"
                    + " positions.\n"
                : "    /** Borrows remaining bytes of a direct buffer; preserves its position.\n")
        .append(
            "     * Caller must keep any backing arena open throughout the call, including"
                + " callbacks.\n")
        .append(
            "     * Liveness/thread checks do not pin the arena against concurrent or reentrant"
                + " closure. */\n")
        .append("    public static ")
        .append(method.returns().java())
        .append(' ')
        .append(method.implementation().name())
        .append('(')
        .append(
            String.join(
                ", ",
                method.arguments().stream()
                    .skip(2)
                    .map(a -> a.carrier().java() + " " + a.name())
                    .toList()))
        .append(") {\n")
        .append(checks)
        .append("        ");
    if (!method.returns().java().equals("void")) out.append("return ");
    out.append(method.name()).append('(').append(String.join(", ", args)).append(");\n    }\n");
  }

  private static void call(JniAbi.Method method, StringBuilder out) {
    Function f = method.implementation();
    String env = cName(method, "env");
    String error = cName(method, "error");
    // A length may precede its buffer, so each buffer's locals are named before any is emitted.
    var lengths = new HashMap<String, String>();
    int position = 0;
    for (Parameter p : f.abiParameters()) {
      String suffix = suffix(method, position++);
      for (BufferBorrow b : method.borrows())
        if (b.parameter().equals(p.name()))
          lengths.put(b.length(), cName(method, "length" + suffix));
    }
    var args = new ArrayList<String>();
    int index = 0;
    for (Parameter p : f.abiParameters()) {
      String suffix = suffix(method, index);
      String name = cName(method, "arg" + index++);
      if (method.buffer(p)) {
        String length = cName(method, "length" + suffix);
        String pointer = cName(method, "pointer" + suffix);
        String empty = cName(method, "empty" + suffix);
        // A null jobject is an invalid buffer, unless the buffer is nullable: then it is an absent
        // one, which keeps the null pointer and length zero where an empty one gets storage.
        boolean nullable = p.nullable();
        out.append("  jlong ")
            .append(length)
            .append(" = ")
            .append(name)
            .append(nullable ? " == NULL ? 0 : (*" : " == NULL ? -1 : (*")
            .append(env)
            .append(")->GetDirectBufferCapacity(")
            .append(env)
            .append(", ")
            .append(name)
            .append(");\n")
            .append("  if ((*")
            .append(env)
            .append(")->ExceptionCheck(")
            .append(env)
            .append(")) return")
            .append(f.returns() == Scalar.VOID ? "" : " 0")
            .append(";\n")
            .append("  void *")
            .append(pointer)
            .append(" = ")
            .append(name)
            .append(" == NULL ? NULL : (*")
            .append(env)
            .append(")->GetDirectBufferAddress(")
            .append(env)
            .append(", ")
            .append(name)
            .append(");\n")
            .append("  if ((*")
            .append(env)
            .append(")->ExceptionCheck(")
            .append(env)
            .append(")) return")
            .append(f.returns() == Scalar.VOID ? "" : " 0")
            .append(";\n")
            .append("  if (")
            .append(length)
            .append(" < 0 || (")
            .append(length)
            .append(" != 0 && ")
            .append(pointer)
            .append(" == NULL)) {\n")
            .append("    jclass ")
            .append(error)
            .append(" = (*")
            .append(env)
            .append(")->FindClass(")
            .append(env)
            .append(", \"java/lang/IllegalArgumentException\");\n")
            .append("    if (")
            .append(error)
            .append(" != NULL) { (*")
            .append(env)
            .append(")->ThrowNew(")
            .append(env)
            .append(", ")
            .append(error)
            .append(", \"invalid direct buffer\"); (*")
            .append(env)
            .append(")->DeleteLocalRef(")
            .append(env)
            .append(", ")
            .append(error)
            .append("); }\n")
            .append("    return")
            .append(f.returns() == Scalar.VOID ? "" : " 0")
            .append(";\n  }\n")
            .append("  uint8_t ")
            .append(empty)
            .append(" = 0;\n  if (")
            .append(nullable ? name + " != NULL && " : "")
            .append(length)
            .append(" == 0) ")
            .append(pointer)
            .append(" = &")
            .append(empty)
            .append(";\n");
        args.add(pointer);
      } else if (method.length(p)) {
        args.add("(" + Types.c(p.type()) + ")" + lengths.get(p.name()));
      } else if (p.type() instanceof Named) {
        args.add("*(" + Types.c(p.type()) + " *)(uintptr_t)" + name);
      } else if (p.type() instanceof Scalar) {
        args.add("(" + Types.c(p.type()) + ")" + name);
      } else {
        args.add("(" + Types.c(p.type()) + ")(uintptr_t)" + name);
      }
    }
    out.append("  ");
    if (f.returns() instanceof Named)
      out.append("*(")
          .append(Types.c(f.returns()))
          .append(" *)(uintptr_t)")
          .append(cName(method, "result"))
          .append(" = ");
    else if (f.returns() != Scalar.VOID) {
      out.append("return (").append(method.returns().c()).append(')');
      if (!(f.returns() instanceof Scalar)) out.append("(uintptr_t)");
    }
    out.append(f.symbol()).append('(').append(String.join(", ", args)).append(");\n");
  }

  /** C has no global-scope qualification: keep wrapper locals from hiding its raw target. */
  private static String cName(JniAbi.Method method, String name) {
    return name.equals(method.implementation().symbol()) ? name + "_" : name;
  }
}
