package dev.elide.myna.backend;

import dev.elide.myna.model.Seam;
import dev.elide.myna.model.Seam.*;
import dev.elide.myna.model.Seam.Module;
import dev.elide.myna.serialize.SeamJson;
import dev.elide.myna.validate.Validator;
import java.util.*;

public final class JavaFfm implements Backend {
  public String filename(Module module) {
    return module.ffmClass() + ".java";
  }

  public String generate(Module m) {
    String ffm = m.ffmClass();
    var functions = new ArrayList<FfmFunction>(m.functions().size());
    for (Function function : m.functions()) functions.add(prepare(m, function));
    // Most functions emit three typed entrypoints. Reserve their usual size, with a bounded
    // initial allocation; unusually large signatures and modules can still grow normally.
    int capacity =
        (int)
            Math.min(
                1_048_576L,
                1024L
                    + functions.size() * 2304L
                    + m.callbacks().size() * 1024L
                    + m.resources().size() * 1024L
                    + m.borrows().size() * 2048L
                    + m.structs().size() * 512L);
    var out =
        new StringBuilder(capacity)
            .append(
                "// Generated by myna; Java 25 FFM.\n"
                    + "package "
                    + m.javaPackageName()
                    + ";\n\n"
                    + "import java.lang.foreign.*;\n"
                    + "import java.lang.invoke.MethodHandle;\n\n"
                    + "public final class "
                    + ffm
                    + " {\n"
                    + "    private "
                    + ffm
                    + "() {}\n");
    out.append("    public static final String ABI_FINGERPRINT = ")
        .append(SeamJson.quote(SeamJson.fingerprint(m)))
        .append(";\n");
    out.append(
        "    static {\n"
            + "        if (ValueLayout.ADDRESS.byteSize() != 8) throw new"
            + " ExceptionInInitializerError(\"64-bit seam target required\");\n"
            + "    }\n");
    for (Struct s : m.structs()) {
      var elements = new ArrayList<String>();
      long offset = 0;
      for (Field f : s.fields()) {
        if (f.offset() > offset)
          elements.add("MemoryLayout.paddingLayout(" + (f.offset() - offset) + ")");
        elements.add(Types.layout(f.type()) + ".withName(\"" + f.name() + "\")");
        offset = f.offset() + Validator.size(f.type());
      }
      if (s.size() > offset)
        elements.add("MemoryLayout.paddingLayout(" + (s.size() - offset) + ")");
      out.append("    public static final StructLayout ")
          .append(s.name())
          .append("_LAYOUT = MemoryLayout.structLayout(\n        ")
          .append(String.join(",\n        ", elements))
          .append(");\n");
      for (Field f : s.fields())
        out.append("    public static final long ")
            .append(s.name())
            .append('_')
            .append(f.name())
            .append("_OFFSET = ")
            .append(f.offset())
            .append("L;\n");
    }
    for (FfmFunction prepared : functions) {
      Function f = prepared.function();
      var args = new ArrayList<String>();
      if (f.returns() != Scalar.VOID) args.add(Types.layout(f.returns()));
      prepared.abiParameters().forEach(p -> args.add(paramLayout(p.type())));
      out.append("    public static final FunctionDescriptor ")
          .append(f.name())
          .append("_DESCRIPTOR = FunctionDescriptor.")
          .append(f.returns() == Scalar.VOID ? "ofVoid(" : "of(")
          .append(String.join(", ", args))
          .append(");\n");
      out.append("    public static MethodHandle ")
          .append(f.name())
          .append(
              "(SymbolLookup lookup) {\n"
                  + "        return Linker.nativeLinker().downcallHandle(lookup.find(")
          .append(prepared.symbol())
          .append(").orElseThrow(() -> new UnsatisfiedLinkError(")
          .append(prepared.symbol())
          .append(")), ")
          .append(f.name())
          .append("_DESCRIPTOR);\n    }\n");
      out.append(
              "    /** Critical calls require the declared bounded, nonblocking, non-reentrant leaf"
                  + " contract. */\n")
          .append("    public static MethodHandle ")
          .append(f.name())
          .append("(SymbolLookup lookup, boolean critical) {\n")
          .append("        if (!critical) return ")
          .append(f.name())
          .append("(lookup);\n");
      if (prepared.leaf()) {
        out.append("        return Linker.nativeLinker().downcallHandle(lookup.find(")
            .append(prepared.symbol())
            .append(").orElseThrow(() -> new UnsatisfiedLinkError(")
            .append(prepared.symbol())
            .append(")), ")
            .append(f.name())
            .append("_DESCRIPTOR, Linker.Option.critical(false));\n");
      } else {
        out.append(
            "        throw new IllegalArgumentException(\"critical downcall requires a native leaf"
                + " contract\");\n");
      }
      out.append("    }\n");
    }
    for (FfmFunction prepared : functions) {
      Function f = prepared.function();
      String carrier = prepared.carrier();
      if (prepared.leaf())
        out.append("    private static final class ")
            .append(f.name())
            .append("_CriticalDowncall {\n")
            .append(
                "        static final MethodHandle HANDLE = Linker.nativeLinker().downcallHandle(")
            .append(ffm)
            .append('.')
            .append(f.name())
            .append("_DESCRIPTOR, Linker.Option.critical(false));\n    }\n");
      out.append(
              "    // ABI adapters may be compiled into an image; addresses remain"
                  + " runtime-bound.\n")
          .append("    private static final class ")
          .append(f.name())
          .append("_Downcall {\n")
          .append(
              "        static final MethodHandle HANDLE = Linker.nativeLinker().downcallHandle(")
          .append(ffm)
          .append('.')
          .append(f.name())
          .append("_DESCRIPTOR);\n    }\n")
          .append("    private static final class ")
          .append(f.name())
          .append("_Binding {\n")
          .append("        static final MemorySegment ADDRESS = SymbolLookup.loaderLookup().find(")
          .append(prepared.symbol())
          .append(").orElseThrow(() -> new UnsatisfiedLinkError(")
          .append(prepared.symbol())
          .append("));\n    }\n")
          .append("    public static ")
          .append(carrier)
          .append(' ')
          .append(f.name())
          .append('(')
          .append(prepared.parameters())
          .append(") throws Throwable {\n        ");
      if (f.returns() != Scalar.VOID) out.append("return (").append(carrier).append(") ");
      out.append(ffm)
          .append('.')
          .append(f.name())
          .append("_Downcall.HANDLE.invokeExact(")
          .append(ffm)
          .append('.')
          .append(f.name())
          .append("_Binding.ADDRESS")
          .append(prepared.arguments().isEmpty() ? "" : ", ")
          .append(prepared.arguments())
          .append(");\n    }\n");
    }
    binding(m, ffm, functions, out, false);
    binding(m, ffm, functions, out, true);
    ownership(m, out);
    FfmCallbacks.generate(m, out);
    return out.append("}\n").toString();
  }

  private static void ownership(Module m, StringBuilder out) {
    if (m.resources().isEmpty()) return;
    out.append(
"""
        @FunctionalInterface
        public interface NativeDestructor { void destroy(MemorySegment address) throws Throwable; }
        /**
         * On successful return, takes sole ownership and returns a non-null consumer owner.
         * On failure, undo registrations without freeing; the generated factory destroys the value.
         * The consumer must keep the library arena alive until destruction, guard all borrows,
         * and enforce requiredThread for access and destruction (null permits shared ownership).
         */
        @FunctionalInterface
        public interface ResourceFactory<T> {
            T adopt(MemorySegment address, NativeDestructor destructor, Thread requiredThread) throws Throwable;
        }
""");
    for (Resource r : m.resources()) {
      Function create =
          m.functions().stream().filter(f -> f.name().equals(r.create())).findFirst().orElseThrow();
      var params = new ArrayList<String>();
      var args = new ArrayList<String>();
      int index = 0;
      for (Parameter p : create.parameters()) {
        String name = "arg" + index++;
        params.add(Types.ffmCarrier(p.type()) + " " + name);
        args.add(name);
      }
      out.append("    public static final class ")
          .append(r.name())
          .append(" {\n")
          .append("        private ")
          .append(r.name())
          .append("() {}\n")
          .append(
              "        public static <T> T create(LibraryBinding binding, ResourceFactory<T>"
                  + " factory")
          .append(params.isEmpty() ? "" : ", " + String.join(", ", params))
          .append(") throws Throwable {\n")
          .append("            java.util.Objects.requireNonNull(factory);\n")
          .append("            MemorySegment address = binding.")
          .append(create.name())
          .append('(')
          .append(String.join(", ", args))
          .append(");\n")
          .append("            if (address.address() == 0) return null;\n")
          .append("            try {\n")
          .append(
              "                return java.util.Objects.requireNonNull(factory.adopt(address,"
                  + " binding::")
          .append(r.destroy())
          .append(", ")
          .append(r.shared() ? "null" : "Thread.currentThread()")
          .append("));\n")
          .append("            } catch (Throwable failure) {\n")
          .append("                try { binding.")
          .append(r.destroy())
          .append("(address); }\n")
          .append(
              "                catch (Throwable cleanup) { if (cleanup != failure)"
                  + " failure.addSuppressed(cleanup); }\n")
          .append("                throw failure;\n            }\n        }\n    }\n");
    }
  }

  /** Instance addresses retain their lookup scope; only the address-free adapters are static. */
  private static void binding(
      Module m, String ffm, List<FfmFunction> prepared, StringBuilder out, boolean critical) {
    String cls = critical ? "CriticalLibraryBinding" : "LibraryBinding";
    var functions = critical ? prepared.stream().filter(FfmFunction::leaf).toList() : prepared;
    out.append(
"""
        /**
         * Explicit library binding. The caller owns the lookup/library arena and must keep it
         * alive for every call and any native values or callbacks that outlive a call.
         * Closing that arena invalidates its symbol segments; FFM rejects subsequent calls.
         * Missing symbols fail only when invoked, allowing import-only libraries.
         */
""")
        .append(
            critical
                ? "        // Only bounded, nonblocking, non-reentrant native leaves are exposed.\n"
                : "")
        .append("        public static final class ")
        .append(cls)
        .append(" {\n");
    for (FfmFunction function : functions) {
      Function f = function.function();
      out.append("        private final java.util.Optional<MemorySegment> ")
          .append(f.name())
          .append("_address;\n");
    }
    out.append("        public ")
        .append(cls)
        .append("(java.nio.file.Path path, Arena arena) {\n")
        .append("            this(SymbolLookup.libraryLookup(path, arena));\n        }\n")
        .append("        public ")
        .append(cls)
        .append("(SymbolLookup lookup) {\n")
        .append("            java.util.Objects.requireNonNull(lookup);\n");
    for (FfmFunction function : functions) {
      Function f = function.function();
      out.append("            this.")
          .append(f.name())
          .append("_address = lookup.find(")
          .append(function.symbol())
          .append(");\n");
    }
    out.append("        }\n");
    for (FfmFunction function : functions) {
      Function f = function.function();
      String carrier = function.carrier();
      out.append("        public ")
          .append(carrier)
          .append(' ')
          .append(f.name())
          .append('(')
          .append(function.parameters())
          .append(") throws Throwable {\n            ");
      if (f.returns() != Scalar.VOID) out.append("return (").append(carrier).append(") ");
      out.append(ffm)
          .append('.')
          .append(f.name())
          .append(critical ? "_CriticalDowncall" : "_Downcall")
          .append(".HANDLE.invokeExact(this.")
          .append(f.name())
          .append("_address.orElseThrow(() -> new UnsatisfiedLinkError(")
          .append(function.symbol())
          .append("))")
          .append(function.arguments().isEmpty() ? "" : ", ")
          .append(function.arguments())
          .append(");\n        }\n");
    }
    for (BufferBorrow borrow : m.borrows())
      if (functions.stream().anyMatch(f -> f.function().name().equals(borrow.function())))
        buffer(m, borrow, out);
    out.append("    }\n");
  }

  private static void buffer(Module m, BufferBorrow borrow, StringBuilder out) {
    Function f =
        m.functions().stream()
            .filter(x -> x.name().equals(borrow.function()))
            .findFirst()
            .orElseThrow();
    Parameter buffer =
        f.parameters().stream()
            .filter(p -> p.name().equals(borrow.parameter()))
            .findFirst()
            .orElseThrow();
    Type length =
        f.parameters().stream()
            .filter(p -> p.name().equals(borrow.length()))
            .findFirst()
            .orElseThrow()
            .type();
    var params = new ArrayList<String>();
    var args = new ArrayList<String>();
    String name = "";
    int index = 0;
    for (Parameter p : f.parameters()) {
      String arg = "arg" + index++;
      if (p == buffer) {
        name = arg;
        params.add("MemorySegment " + arg);
        args.add("pointer");
      } else if (p.name().equals(borrow.length())) {
        args.add(length == Scalar.I32 || length == Scalar.U32 ? "(int) length" : "length");
      } else {
        params.add(Types.ffmCarrier(p.type()) + " " + arg);
        args.add(arg);
      }
    }
    out.append(
            "        /** Borrows the entire native segment for this call; length is in bytes. */\n")
        .append("        public ")
        .append(Types.ffmCarrier(f.returns()))
        .append(' ')
        .append(f.name())
        .append('(')
        .append(String.join(", ", params))
        .append(") throws Throwable {\n")
        .append("            if (!")
        .append(name)
        .append(".isNative()) throw new IllegalArgumentException(\"native segment required\");\n");
    if (buffer.access() == Access.READ_WRITE)
      out.append("            if (")
          .append(name)
          .append(
              ".isReadOnly()) throw new IllegalArgumentException(\"writable segment"
                  + " required\");\n");
    out.append("            if (!")
        .append(name)
        .append(".scope().isAlive()) throw new IllegalStateException(\"closed buffer\");\n")
        .append("            if (!")
        .append(name)
        .append(".isAccessibleBy(Thread.currentThread())) throw new WrongThreadException();\n")
        .append("            long length = ")
        .append(name)
        .append(".byteSize();\n");
    out.append("            if (length != 0 && ")
        .append(name)
        .append(".address() == 0) throw new IllegalArgumentException(\"null buffer address\");\n");
    if (length == Scalar.I32 || length == Scalar.U32)
      out.append("            if (length > ")
          .append(length == Scalar.I32 ? "2147483647L" : "4294967295L")
          .append(") throw new IllegalArgumentException(\"buffer length exceeds ABI range\");\n");
    out.append("            if (length != 0) {\n")
        .append("                MemorySegment pointer = ")
        .append(name)
        .append(";\n                ");
    if (f.returns() != Scalar.VOID) out.append("return ");
    out.append("this.").append(f.name()).append('(').append(String.join(", ", args)).append(");\n");
    if (f.returns() == Scalar.VOID) out.append("                return;\n");
    out.append("            }\n")
        .append("            try (Arena empty = Arena.ofConfined()) {\n")
        .append("                MemorySegment pointer = empty.allocate(1);\n                ");
    if (f.returns() != Scalar.VOID) out.append("return ");
    out.append("this.")
        .append(f.name())
        .append('(')
        .append(String.join(", ", args))
        .append(");\n            }\n        }\n");
  }

  /**
   * FFM passes records by value natively, so only exports (which Native Image publishes in
   * reference form) are lowered.
   */
  private static Function ffmForm(Module m, Function f) {
    return f.direction() == Direction.EXPORT ? ByValue.lower(m, f) : f;
  }

  /** Per-emission formatting shared by the static, scoped and critical entrypoints. */
  private record FfmFunction(
      Function function,
      List<Parameter> abiParameters,
      String symbol,
      String carrier,
      String parameters,
      String arguments,
      boolean leaf) {}

  private static FfmFunction prepare(Module m, Function original) {
    Function f = ffmForm(m, original);
    List<Parameter> abiParameters = f.abiParameters();
    var parameters = new StringJoiner(", ");
    var arguments = new StringJoiner(", ");
    if (f.returns() instanceof Named) {
      String allocator = allocatorParameter(abiParameters);
      parameters.add("SegmentAllocator " + allocator);
      arguments.add(allocator);
    }
    for (Parameter p : abiParameters) {
      parameters.add(Types.ffmCarrier(p.type()) + " " + p.name());
      arguments.add(widened(p.type(), p.name()));
    }
    return new FfmFunction(
        f,
        abiParameters,
        SeamJson.quote(f.symbol()),
        Types.ffmCarrier(f.returns()),
        parameters.toString(),
        arguments.toString(),
        Seam.nativeLeaf(f));
  }

  private static String allocatorParameter(List<Parameter> parameters) {
    var names = parameters.stream().map(Parameter::name).toList();
    String name = "allocator";
    while (names.contains(name)) name += "_";
    return name;
  }

  private static boolean unsignedSmall(Type t) {
    return t == Scalar.U8 || t == Scalar.U16;
  }

  /** A downcall sign-extends narrow signed carriers, so u8/u16 pass as a zero-extended int. */
  private static String paramLayout(Type type) {
    return unsignedSmall(type) ? "ValueLayout.JAVA_INT" : Types.layout(type);
  }

  private static String widened(Type t, String value) {
    if (t == Scalar.U8) return value + " & 0xff";
    if (t == Scalar.U16) return value + " & 0xffff";
    return value;
  }
}
