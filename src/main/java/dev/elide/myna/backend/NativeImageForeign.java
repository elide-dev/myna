package dev.elide.myna.backend;

import dev.elide.myna.model.Seam;
import dev.elide.myna.model.Seam.Function;
import dev.elide.myna.model.Seam.Module;

/**
 * Registers known FFM ABI shapes with Native Image before analysis; addresses stay runtime-bound.
 */
public final class NativeImageForeign implements Backend {
  public String filename(Module module) {
    return module.foreignFeatureClass() + ".java";
  }

  public String generate(Module module) {
    String pkg = module.javaPackageName(), ffm = module.ffmClass();
    String downcall = "        RuntimeForeignAccess.registerForDowncall(" + ffm + '.';
    String buildTime =
        "        RuntimeClassInitialization.initializeAtBuildTime(\"" + pkg + '.' + ffm + '$';
    String runTime =
        "        RuntimeClassInitialization.initializeAtRunTime(\"" + pkg + '.' + ffm + '$';
    // Registration text is proportional to the ABI surface. Avoid copying the growing output
    // for ordinary modules, without making an unbounded speculative allocation for large inputs.
    int capacity =
        (int)
            Math.min(
                1_048_576L,
                512L + module.functions().size() * 512L + module.callbacks().size() * 384L);
    var out =
        new StringBuilder(capacity)
            .append(
                "// Generated by myna. Enable only in Native Image applications using the FFM"
                    + " bindings.\n"
                    + "package "
                    + pkg
                    + ";\n\n"
                    + "import org.graalvm.nativeimage.hosted.Feature;\n"
                    + "import org.graalvm.nativeimage.hosted.RuntimeClassInitialization;\n"
                    + "import org.graalvm.nativeimage.hosted.RuntimeForeignAccess;\n\n"
                    + "public final class "
                    + module.foreignFeatureClass()
                    + " implements Feature {\n"
                    + "    @Override public void duringSetup(DuringSetupAccess access) {\n")
            // The outer class holds only descriptors, layouts and the fingerprint. Initializing it
            // at build time removes a class-initialization check from every static entry call.
            .append("        RuntimeClassInitialization.initializeAtBuildTime(\"")
            .append(pkg)
            .append('.')
            .append(ffm)
            .append("\");\n");
    for (Function function : module.functions()) {
      out.append(downcall).append(function.name()).append("_DESCRIPTOR);\n");
      if (Seam.nativeLeaf(function)) {
        out.append(downcall)
            .append(function.name())
            .append("_DESCRIPTOR, java.lang.foreign.Linker.Option.critical(false));\n");
        out.append(buildTime).append(function.name()).append("_CriticalDowncall\");\n");
      }
      out.append(buildTime).append(function.name()).append("_Downcall\");\n");
      out.append(runTime).append(function.name()).append("_Binding\");\n");
    }
    for (var callback : module.callbacks()) {
      out.append("        RuntimeForeignAccess.registerForUpcall(")
          .append(ffm)
          .append('.')
          .append(callback.name())
          .append("_CALLBACK_DESCRIPTOR);\n")
          .append(buildTime)
          .append(callback.name())
          .append("Upcalls\");\n");
      if (callback.ffmTarget() != null)
        out.append("        RuntimeForeignAccess.registerForDirectUpcall(")
            .append(ffm)
            .append('.')
            .append(callback.name())
            .append("Upcalls.STATIC_HANDLE, ")
            .append(ffm)
            .append('.')
            .append(callback.name())
            .append("_CALLBACK_DESCRIPTOR);\n");
    }
    return out.append("    }\n}\n").toString();
  }
}
